"""Мост к движку MM2: здесь только запуск, вся механика — в roblox-swap.

Почему так, а не «допишем сценарий здесь». MM2 переехал в своп-проект целиком:
там каталог из 943 позиций, журнал операций с точкой невозврата, очередь выдачи
с пересменкой, библиотека эталонов и правила отказа. Всё это завязано на учёт —
на то, что склад ЗНАЕТ, что лежит на аккаунте. Держать рядом вторую реализацию
значит однажды выдать вещь по той, которая не знает про журнал.

Что осталось здесь и почему это правильно: brainbot — это глаза, руки и клиент.
Захват окна, OCR, ввод, мьютекс, уступка ввода пользователю, поднятие аккаунта.
Движок MM2 их и импортирует. Обратная сторона — запуск: человек работает из
`python run.py`, и незачем заставлять его помнить чужой путь и чужие модули.

Поэтому мост процессный, а не импортный: мы не тянем движок в свой процесс, а
запускаем его инструмент тем же интерпретатором, из его папки. Кольцевой
зависимости не возникает (движок импортирует brainbot, brainbot движок — нет),
и версии не склеиваются: обновился своп — обновился и запуск.

Путь к движку берётся, по порядку: `--engine`, переменная `ROBLOX_SWAP`, сосед
`../старпепс/roblox-swap`. Не нашли — говорим прямо, а не «инструмент не
существует».
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

# Инструменты движка, которые имеет смысл звать отсюда. Список закрытый: опечатка
# в имени модуля иначе превращается в невнятную ошибку импорта у питона.
TOOLS = {
    "join": "зайти в игру или в приватку",
    "probe": "посмотреть экран, ничего не нажимая",
    "poke": "один клик или клавиша по месту из схемы",
    "invite": "позвать контрагента в комнату",
    "deal": "обмен: снять инвентарь, отдать, принять",
    "teach": "разбор накопленных чтений OCR",
    "learn_icons": "библиотека эталонов: запомнить, как предмет выглядит",
}

СОСЕД = Path(__file__).resolve().parents[3] / "старпепс" / "roblox-swap"


def _движок_ли(папка: Path) -> bool:
    return (папка / "agents" / "mm2" / "tools").is_dir()


def найти_движок(указанный: str | None = None) -> Path:
    """Папка roblox-swap. Ошибка здесь понятнее, чем ImportError внутри.

    Названный путь не подменяется соседним. Проекты лежат рядом, и «показали не
    на тот, молча взяли другой» — это запуск не той версии движка: в одной папке
    может быть ветка с журналом, в другой без.
    """
    if указанный:
        папка = Path(указанный).expanduser()
        if _движок_ли(папка):
            return папка
        raise SystemExit(f"В {папка} движка MM2 нет (ждали agents/mm2/tools).")

    for кандидат in (os.environ.get("ROBLOX_SWAP"), СОСЕД):
        if кандидат and _движок_ли(Path(кандидат).expanduser()):
            return Path(кандидат).expanduser()
    raise SystemExit(
        "Движок MM2 не найден. Он живёт в отдельном проекте roblox-swap:\n"
        f"   искали: $ROBLOX_SWAP, {СОСЕД}\n"
        "   укажи путь: python run.py mm2 --engine \"D:\\claude projects\\старпепс\\roblox-swap\" …"
    )


def run(tool: str, argv: list[str], *, engine: str | None = None) -> int:
    """Запустить инструмент движка и вернуть его код возврата.

    Вывод не перехватываем: инструменты движка разговаривают с человеком сами, и
    пересказ их слов — лишний слой, в котором теряются причины отказа.
    """
    if tool not in TOOLS:
        raise SystemExit(f"Неизвестный инструмент {tool!r}. Есть: {', '.join(sorted(TOOLS))}")
    папка = найти_движок(engine)
    команда = [sys.executable, "-m", f"agents.mm2.tools.{tool}", *argv]
    return subprocess.call(команда, cwd=str(папка))
