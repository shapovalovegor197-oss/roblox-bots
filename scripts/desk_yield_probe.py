# -*- coding: utf-8 -*-
"""Два вопроса разом, на которых держится вся затея с рабочими столами.

1. **Доходит ли ввод бота** до клиента, который живёт на невидимом столе, пока
   человек работает на своём. Меряем не «послали», а сдвиг картинки: поворот
   камеры обязан менять кадр.
2. **Видит ли бот ввод человека** с ДРУГОГО стола. Уступка (`yield_to_user`)
   стоит на низкоуровневых хуках, а те ставятся на очередь ввода своего стола.
   Если хук чужой стол не видит — уступка на выделенном столе не сработает
   никогда, и это ровно то, что нам нужно: человек печатает у себя, бот играет
   у себя.

   Обратный исход тоже важен и его нельзя пропустить: если хук ВИДИТ чужой
   ввод, бот будет замирать каждый раз, когда человек трогает мышь, и польза
   от стола теряется.

Прогон 90 секунд. Человека просим первые ~30 секунд не трогать мышь, а потом
активно печатать — в отчёте это видно как перелом в колонке «с ввода».

Запускается НА своём столе: `desktop.spawn` из `desk_probe_run.py`.
"""
import sys
import time

sys.path.insert(0, "src")

import numpy as np                                          # noqa: E402

from brainbot import capture, config, desktop, log          # noqa: E402
from brainbot.inputs import Hand                            # noqa: E402
from brainbot.useractivity import UserActivity              # noqa: E402
from brainbot.window import enum_roblox_windows             # noqa: E402

секунд = float(sys.argv[1]) if len(sys.argv) > 1 else 90.0

s = config.load()
log.setup(s.logs_dir)
стол = desktop.current()
print("стол: %r" % стол, flush=True)

окна = enum_roblox_windows()
print("окон Roblox на этом столе: %d" % len(окна), flush=True)
if not окна:
    sys.exit("клиента на этом столе нет — запускать замер не на чем")
win = окна[0]
print("окно hwnd=%s, клиентская область %sx%s"
      % (win.hwnd, win.client_box().width, win.client_box().height), flush=True)

# Уступку выключаем НАМЕРЕННО: она бы остановила бота, и мы не узнали бы,
# доходит ли ввод. Монитор живого ввода при этом крутим сами и только смотрим
# на него.
cfg = dict(s.input)
cfg["yield_to_user"] = False
hand = Hand(win, cfg)
монитор = UserActivity().start()


def кадр():
    return capture.grab(win.client_box(), win.hwnd)


# Зрение проверяем ПЕРВЫМ делом и отдельно. На выделенном столе композитор окна
# не рисует, и все три пути захвата отваливаются по-разному: WGC отдаёт
# 0x80070057, dxcam требует вывода на экран, mss делает BitBlt по экранным
# координатам, которых у невидимого стола нет. Замер 19.09: 0 кадров из 26
# попыток на столе против живого кадра 1280x720 у того же клиента на видимом.
try:
    первый = кадр()
    print("зрение есть: кадр %sx%s" % (первый.shape[1], первый.shape[0]), flush=True)
except Exception as exc:                                    # noqa: BLE001
    print("ЗРЕНИЯ НЕТ на столе %r: %s" % (стол, str(exc)[:120]), flush=True)
    print("Бот здесь слеп, мерить ввод бессмысленно. Клиент на выделенном "
          "столе не композитится — см. память про изоляцию столами.", flush=True)
    sys.exit(3)


print("\n  время | с ввода | фокус наш | сдвиг кадра от поворота", flush=True)
начало = time.time()
итоги = []
while time.time() - начало < секунд:
    до = кадр()
    hand.look(400, 0)                       # поворот камеры вправо
    time.sleep(0.45)
    после = кадр()
    сдвиг = float(np.mean(np.abs(после.astype(np.int16) - до.astype(np.int16))))
    с_ввода = монитор.seconds_since()
    фокус = win.is_foreground()
    прошло = time.time() - начало
    итоги.append((прошло, с_ввода, фокус, сдвиг))
    print("  %5.0f | %7s | %9s | %6.2f"
          % (прошло,
             "-" if с_ввода > 1e8 else "%.1f" % с_ввода,
             "да" if фокус else "НЕТ",
             сдвиг), flush=True)
    time.sleep(2.0)

print("\n=== ИТОГ ===", flush=True)
дошло = [x for x in итоги if x[3] > 1.0]
print("поворотов сделано: %d, кадр изменился: %d" % (len(итоги), len(дошло)), flush=True)
видел = [x for x in итоги if x[1] < 1e8]
if видел:
    print("монитор ЗАМЕТИЛ живой ввод: %d замеров из %d, самый свежий %.1f с"
          % (len(видел), len(итоги), min(x[1] for x in видел)), flush=True)
    print("значит уступка на выделенном столе СРАБОТАЕТ — бот будет замирать, "
          "когда человек за компом", flush=True)
else:
    print("монитор НЕ ВИДЕЛ живого ввода ни разу за весь прогон", flush=True)
    print("значит хук чужой стол не видит: бот на своём столе человеку не "
          "мешает и от его работы не замирает", flush=True)
print("ГОТОВО", flush=True)
