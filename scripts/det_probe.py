# -*- coding: utf-8 -*-
"""Опыт «форсированный детерминизм»: нужен ли вообще пеленг перед локом.

Гипотеза, снятая с референсного макроса (Namesnipes, разбор 03.09). Он до
плиты НЕ ИЩЕТ дорогу: респавн ставит персонажа в спавн базы, камера кладётся
строго вертикальной протяжкой (рысканье при этом не меняется), и дальше идёт
слепое счисление — `d` на 1.8 с. Зрение нужно ровно на один бит: плот слева
или справа. Работает это потому, что рысканье не трогают ВООБЩЕ: горизонтально
мышь не ведут ни разу, значит после респавна взгляд тот же, что и был.

Зачем нам. За ночь 03.09: 41 «сверху пад не опознан» и 18 «свечения плиты не
видно даже осмотром». Это те круги, где лок не встал и дверь стояла открытой
сериями до 694 с — то самое окно, в которое нас обносят. Если слепой ход
доходит до плиты, весь слой распознавания уходит из критического пути лока.

Что этот скрипт НЕ делает: не правит ни строки в src/. Он только мерит. Решение
о переносе в боевой код принимается по напечатанным числам, не раньше.
Точка возврата на всякий случай: git tag before-determinism.

Инвариант, на котором всё держится: пока мы ходим ТОЛЬКО через `hand.hold`
(она держит ПКМ, но мышь не ведёт), рысканье камеры не меняется. Любой `look`,
`turn_degrees`, `pitch_*` его ломает — в слепой ветке их быть не должно.

Три ступени, каждая отдельным запуском:

    python scripts/det_probe.py yaw 10
        Дёшево убить гипотезу. Респавн возвращает вид на то же место? Меряем
        сдвиг сцены между кадрами «сразу после респавна» разных итераций. Вид
        гуляет — слепой ход невозможен в принципе, дальше идти незачем.

    python scripts/det_probe.py route
        Перебор: какая клавиша и сколько секунд от спавна доводят до плиты.
        Оценка — ответ САМОЙ ИГРЫ на нажатие E, а не наш детектор пада.

    python scripts/det_probe.py blind d 1.8 10
        Слепой повтор найденного: сколько попаданий из N и за сколько секунд.
        Сравнивать с замером закрытого цикла: 17.6 с на лок (03.09, 12:20).
"""
import sys
import time

import cv2
import numpy as np

sys.path.insert(0, "src")
from brainbot import config, log, ocr, single                    # noqa: E402
from brainbot.farm import Farmer, FarmTuning                     # noqa: E402
from brainbot.inputs import Hand                                 # noqa: E402
from brainbot.window import enum_roblox_windows                  # noqa: E402

# Ответы игры на E у плиты. Оба означают одно и то же для опыта: МЫ ДОШЛИ.
# Второй нужен потому, что лок держится ~80 с, и без него каждый повтор
# пришлось бы ждать истечения — 10 повторов превратились бы в 15 минут.
ОТВЕТЫ = ("locked your base", "already locked")

# Полоса HUD, где игра пишет оба ответа (замер 30.08: y=0.867, x=0.498).
ПОЛОСА = (0.20, 0.78, 0.80, 0.97)


def подключиться():
    """Клиент, окно рабочего размера, Farmer. Без этого мерить нечего."""
    s = config.load()
    log.setup(s.logs_dir)
    wins = enum_roblox_windows()
    if not wins:
        sys.exit("окон Roblox нет — клиент не запущен")
    win = wins[0]
    box = win.client_box()
    want = int(s.window["width"]), int(s.window["height"])
    if (box.width, box.height) != want:
        sys.exit("окно %dx%d, а зрение считает долями от %dx%d — сперва "
                 "python scripts/fix_window.py" % (box.width, box.height, *want))
    f = Farmer(window=win, hand=Hand(win, s.input), tuning=FarmTuning(),
               screens_dir=s.screenshots_dir)
    return f


def сдвиг(a, b):
    """Насколько вид b повёрнут относительно a: (dx пикселей, dy, отклик).

    Фазовая корреляция по той же вырезке, что и в nav._scene_shift, но своя:
    там при |dx|<3 возвращается None, и «идеальное совпадение» неотличимо от
    «не понять». Для этого опыта разница принципиальна — совпадение и есть
    искомый результат.
    """
    ga = cv2.cvtColor(a, cv2.COLOR_BGR2GRAY)[120:600, 160:1120].astype(np.float32)
    gb = cv2.cvtColor(b, cv2.COLOR_BGR2GRAY)[120:600, 160:1120].astype(np.float32)
    if ga.shape != gb.shape:
        return None
    (dx, dy), отклик = cv2.phaseCorrelate(ga, gb)
    return float(dx), float(dy), float(отклик)


def ответ_игры(f, ждать: float = 2.5) -> str | None:
    """Что игра ответила на E: одна из строк ОТВЕТЫ или None.

    Читаем узкую полосу HUD, а не кадр целиком: полный OCR 1280x720 стоит
    полсекунды, а спрашивать надо часто и сразу после нажатия — вспышка живёт
    несколько секунд и гаснет.
    """
    край = time.time() + ждать
    while time.time() < край:
        кадр = f.frame()
        h, w = кадр.shape[:2]
        x0, y0, x1, y1 = ПОЛОСА
        полоса = кадр[int(y0 * h):int(y1 * h), int(x0 * w):int(x1 * w)]
        текст = ocr.all_text(полоса).lower()
        for нужное in ОТВЕТЫ:
            if нужное in текст:
                return нужное
        time.sleep(0.3)
    return None


def дошли(f) -> str | None:
    """Нажать E и спросить игру, стояли ли мы на плите."""
    f.hand.interact(1.4)
    return ответ_игры(f)


# ----------------------------------------------------------------------
# Ступень 1: рысканье переживает респавн?
# ----------------------------------------------------------------------

def ступень_рысканье(f, n: int) -> None:
    print("=== ступень 1: тот же ли вид после респавна (%d итераций) ===" % n,
          flush=True)
    print("камеру не трогаю ВООБЩЕ: только респавн и ходьба удержанием",
          flush=True)
    эталон = None
    годных = 0
    fov = f.nav.effective_fov(1280, 720)
    for i in range(1, n + 1):
        t0 = time.time()
        f.reset_to_base()
        time.sleep(0.5)
        кадр = f.frame()
        if эталон is None:
            эталон = кадр
            f.shot("det_yaw_эталон")
            print("итерация 1: эталон снят (%.1f с)" % (time.time() - t0),
                  flush=True)
        else:
            рез = сдвиг(эталон, кадр)
            if рез is None:
                print("итерация %d: кадры разного размера — пропуск" % i, flush=True)
                continue
            dx, dy, отклик = рез
            град = dx / 1280.0 * fov
            ок = abs(dx) <= 40 and отклик >= 0.05
            годных += int(ок)
            print("итерация %2d: dx=%+7.1f px (%+5.1f град)  dy=%+6.1f  "
                  "отклик=%.3f  %s (%.1f с)"
                  % (i, dx, град, dy, отклик, "СОВПАЛ" if ок else "УЕХАЛ",
                     time.time() - t0), flush=True)
            if not ок:
                f.shot("det_yaw_уехал_%d" % i)
        # Отойти, чтобы следующий респавн действительно возвращал, а не
        # заставал нас на том же месте. Ходьба удержанием рысканье не трогает.
        f.hand.hold("w", 1.5)
        time.sleep(0.3)
    всего = n - 1
    print("--- ИТОГ: совпало %d из %d" % (годных, всего), flush=True)
    print("порог гипотезы: 8 из 10. Меньше — слепой ход невозможен, "
          "распознавание из лока не убирать.", flush=True)


# ----------------------------------------------------------------------
# Ступень 2: чем и сколько идти от спавна до плиты
# ----------------------------------------------------------------------

def ступень_маршрут(f, клавиши=("d", "a", "w", "s"),
                    сроки=(0.6, 1.0, 1.4, 1.8, 2.2, 2.6)) -> None:
    print("=== ступень 2: слепой маршрут от спавна до плиты ===", flush=True)
    # Один раз подсматриваем свечение плиты — не чтобы идти по нему, а чтобы
    # не перебирать все четыре стороны вслепую. Если не видно — перебираем.
    f.reset_to_base()
    time.sleep(0.5)
    свеч = f.plate_glow(f.frame())
    порядок = list(клавиши)
    if свеч:
        x = свеч[0]
        порядок = (["d", "w", "a", "s"] if x > 0.55 else
                   ["a", "w", "d", "s"] if x < 0.45 else ["w", "d", "a", "s"])
        print("свечение плиты видно на x=%.2f — начинаю с %r" % (x, порядок[0]),
              flush=True)
    else:
        print("свечения не видно — перебираю все стороны", flush=True)

    for клавиша in порядок:
        for срок in сроки:
            t0 = time.time()
            f.reset_to_base()
            time.sleep(0.4)
            f.hand.hold(клавиша, срок)
            time.sleep(0.4)
            ответ = дошли(f)
            print("%s %.1f с -> %s (%.1f с)"
                  % (клавиша, срок, ответ or "мимо", time.time() - t0), flush=True)
            if ответ:
                print("--- НАШЁЛ: %s на %.1f с. Проверять повтором:" % (клавиша, срок),
                      flush=True)
                print("    python scripts/det_probe.py blind %s %.1f 10"
                      % (клавиша, срок), flush=True)
                return
    print("--- маршрут не найден: ни одна пара «клавиша, срок» не довела",
          flush=True)


# ----------------------------------------------------------------------
# Ступень 3: слепой повтор — сколько попаданий из N
# ----------------------------------------------------------------------

def ступень_слепая(f, клавиша: str, срок: float, n: int) -> None:
    print("=== ступень 3: слепой повтор %s на %.1f с, %d раз ==="
          % (клавиша, срок, n), flush=True)
    попаданий = 0
    времена = []
    for i in range(1, n + 1):
        t0 = time.time()
        f.reset_to_base()
        time.sleep(0.4)
        f.hand.hold(клавиша, срок)
        time.sleep(0.4)
        ответ = дошли(f)
        dt = time.time() - t0
        времена.append(dt)
        попаданий += int(bool(ответ))
        print("повтор %2d: %-22s %.1f с" % (i, ответ or "МИМО", dt), flush=True)
        if not ответ:
            f.shot("det_blind_мимо_%d" % i)
    средн = sum(времена) / len(времена) if времена else 0
    print("--- ИТОГ: дошли %d из %d, в среднем %.1f с на заход"
          % (попаданий, n, средн), flush=True)
    print("сравнение: закрытый цикл 03.09 давал лок за 17.6 с "
          "(таблица 0.9, разворот 0.0, наведение 0.5, подход 2.5, дошаг 1.1 "
          "плюс респавн 5.4 и камера 8.1)", flush=True)


def main() -> None:
    если_не = "yaw N | route | blind КЛАВИША СЕКУНДЫ N"
    if len(sys.argv) < 2:
        sys.exit("как запускать: python scripts/det_probe.py " + если_не)
    режим = sys.argv[1]
    single.занять("det_probe")
    f = подключиться()
    try:
        if режим == "yaw":
            ступень_рысканье(f, int(sys.argv[2]) if len(sys.argv) > 2 else 10)
        elif режим == "route":
            ступень_маршрут(f)
        elif режим == "blind":
            if len(sys.argv) < 4:
                sys.exit("blind КЛАВИША СЕКУНДЫ [N]")
            ступень_слепая(f, sys.argv[2], float(sys.argv[3]),
                           int(sys.argv[4]) if len(sys.argv) > 4 else 10)
        else:
            sys.exit("непонятный режим %r: " % режим + если_не)
    finally:
        # Последнее действие ЛЮБОГО опыта: закрыть дверь. Пока база открыта,
        # у нас уносят брейнротов, и цена этому уже измерена.
        f.hand.release_all()
        single.запереть_базу(f)


if __name__ == "__main__":
    main()
