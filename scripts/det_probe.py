def разница(a, b) -> float:
    """Доля заметно изменившихся пикселей: 0 — тот же вид, 1 — другой.

    Фазовая корреляция для этого не годится, и это выяснилось замером: на
    разных сценах её отклик падает до 0.01, dx становится случайным (в первом
    прогоне «+290 px, +15.9 град» при том, что кадры просто разные), и признак
    «камера повернулась» неотличим от признака «мы смотрим в другое место».
    Доля изменившихся пикселей врать так не умеет.
    """
    ga = cv2.cvtColor(a, cv2.COLOR_BGR2GRAY)[120:600, 160:1120].astype(np.int16)
    gb = cv2.cvtColor(b, cv2.COLOR_BGR2GRAY)[120:600, 160:1120].astype(np.int16)
    if ga.shape != gb.shape:
        return 1.0
    return float((np.abs(ga - gb) > 25).mean())


def устойчивый_кадр(f, предел: float = 5.0):
    """Кадр, снятый ПОСЛЕ того, как картинка встала.

    Первый прогон дал «разница 0.56» между двумя видами с одного места, и это
    оказалась не камера: эталон поймали в момент, когда тело ещё лежало на полу
    после смерти. Ждать фиксированные полсекунды нельзя — анимация возрождения
    длится по-разному. Ждём, пока два кадра подряд не совпадут.
    """
    край = time.time() + предел
    прежний = None
    кадр = f.frame()
    while time.time() < край:
        time.sleep(0.35)
        кадр = f.frame()
        if прежний is not None and разница(прежний, кадр) < 0.02:
            return кадр
        прежний = кадр
    return кадр


def кадр_после_воскрешения(f, предел: float = 14.0):
    """Кадр, снятый когда тело УЖЕ ВСТАЛО, а не пока лежит.

    Находка замера 04.09: `reset_to_base` возвращает управление, пока персонаж
    ещё мёртв. Камера смерти стоит на месте и картинка при этом устойчива, так
    что проверка «кадр перестал меняться» её пропускает. Кадр 01:08:36 — вид с
    земли на площадь, персонажа в кадре НЕТ ВООБЩЕ, и по такому кадру бот
    честно не находит ни пад, ни свечение.

    Ловим сам момент воскрешения: мир скачком меняется, и уже после этого ждём,
    пока встанет. Пять из шести кадров прошлого замера были камерой смерти —
    отсюда и «разница 0.53» при рысканье, не сдвинувшемся ни на пиксель.
    """
    прежний = устойчивый_кадр(f, 4.0)
    край = time.time() + предел
    while time.time() < край:
        time.sleep(0.3)
        текущий = f.frame()
        if разница(прежний, текущий) > 0.25:
            return устойчивый_кадр(f, 4.0)
        прежний = текущий
    return прежний


def ступень_рысканье(f, n: int, ходьба: float = 1.5) -> None:
    print("=== ступень 1: тот же ли вид после респавна (%d итераций) ===" % n,
          flush=True)
    print("камеру не трогаю ВООБЩЕ: только респавн%s"
          % (" и ходьба удержанием %.1f с" % ходьба if ходьба else
             " (ходьбы между итерациями НЕТ — изолирую сам респавн)"),
          flush=True)
    эталон = None
    годных = 0
    fov = f.nav.effective_fov(1280, 720)
    for i in range(1, n + 1):
        t0 = time.time()
        f.reset_to_base()
        кадр = кадр_после_воскрешения(f)
        if эталон is None:
            эталон = кадр
            f.shot("det_yaw_эталон")
            print("итерация 1: эталон снят (%.1f с)" % (time.time() - t0),
                  flush=True)
        else:
            рез = сдвиг(эталон, кадр)
            if рез is None:
                print("итерация %d: кадры разного размера — пропуск" % i, flush=True)
                continue
            dx, dy, отклик = рез
            град = dx / 1280.0 * fov
            дельта = разница(эталон, кадр)
            ок = дельта <= 0.15
            годных += int(ок)
            print("итерация %2d: разница %.3f  %s   (справочно: dx=%+7.1f px "
                  "%+5.1f град, отклик=%.3f)  (%.1f с)"
                  % (i, дельта, "ТОТ ЖЕ ВИД" if ок else "ДРУГОЙ ВИД",
                     dx, град, отклик, time.time() - t0), flush=True)
            if not ок:
                f.shot("det_yaw_уехал_%d" % i)
        # Отойти, чтобы следующий респавн действительно возвращал, а не
        # заставал нас на том же месте. Ходьба удержанием рысканье не трогает.
        if ходьба:
            f.hand.hold("w", ходьба)
            time.sleep(0.3)
    всего = n - 1
    print("--- ИТОГ: совпало %d из %d" % (годных, всего), flush=True)
    print("порог гипотезы: 8 из 10. Меньше — слепой ход невозможен, "
          "распознавание из лока не убирать.", flush=True)


# ----------------------------------------------------------------------
# Ступень 2: чем и сколько идти от спавна до плиты
# ----------------------------------------------------------------------

def ступень_маршрут(f, клавиши=("d", "a", "w", "s"),
                    сроки=(0.6, 1.0, 1.4, 1.8, 2.2, 2.6)) -> None:
    print("=== ступень 2: слепой маршрут от спавна до плиты ===", flush=True)
    # Один раз подсматриваем свечение плиты — не чтобы идти по нему, а чтобы
    # не перебирать все четыре стороны вслепую. Если не видно — перебираем.
    f.reset_to_base()
    кадр_после_воскрешения(f)
    свеч = f.plate_glow(f.frame())
    порядок = list(клавиши)
    if свеч:
        x = свеч[0]
        порядок = (["d", "w", "a", "s"] if x > 0.55 else
                   ["a", "w", "d", "s"] if x < 0.45 else ["w", "d", "a", "s"])
        print("свечение плиты видно на x=%.2f — начинаю с %r" % (x, порядок[0]),
              flush=True)
    else:
        print("свечения не видно — перебираю все стороны", flush=True)

    for клавиша in порядок:
        for срок in сроки:
            t0 = time.time()
            f.reset_to_base()
            кадр_после_воскрешения(f)
            f.hand.hold(клавиша, срок)
            time.sleep(0.4)
            ок, оц, текст = дошли(f)
            print("%s %.1f с -> %s  оценка %.2f  %r  (%.1f с)"
                  % (клавиша, срок, "ДОШЁЛ" if ок else "мимо", оц, текст[:50],
                     time.time() - t0), flush=True)
            if ок:
                print("--- НАШЁЛ: %s на %.1f с. Проверять повтором:" % (клавиша, срок),
                      flush=True)
                print("    python scripts/det_probe.py blind %s %.1f 10"
                      % (клавиша, срок), flush=True)
                return
    print("--- маршрут не найден: ни одна пара «клавиша, срок» не довела",
          flush=True)


# ----------------------------------------------------------------------
# Ступень 3: слепой повтор — сколько попаданий из N
# ----------------------------------------------------------------------

def ступень_слепая(f, клавиша: str, срок: float, n: int) -> None:
    print("=== ступень 3: слепой повтор %s на %.1f с, %d раз ==="
          % (клавиша, срок, n), flush=True)
    попаданий = 0
    времена = []
    for i in range(1, n + 1):
        t0 = time.time()
        f.reset_to_base()
        кадр_после_воскрешения(f)
        f.hand.hold(клавиша, срок)
        time.sleep(0.4)
        ок, оц, текст = дошли(f)
        dt = time.time() - t0
        времена.append(dt)
        попаданий += int(ок)
        print("повтор %2d: %-7s оценка %.2f  %r  %.1f с"
              % (i, "ДОШЁЛ" if ок else "МИМО", оц, текст[:40], dt), flush=True)
        if not ок:
            f.shot("det_blind_мимо_%d" % i)
    средн = sum(времена) / len(времена) if времена else 0
    print("--- ИТОГ: дошли %d из %d, в среднем %.1f с на заход"
          % (попаданий, n, средн), flush=True)
    print("сравнение: закрытый цикл 03.09 давал лок за 17.6 с "
          "(таблица 0.9, разворот 0.0, наведение 0.5, подход 2.5, дошаг 1.1 "
          "плюс респавн 5.4 и камера 8.1)", flush=True)


def ступень_диагностика(f, клавиша: str, срок: float) -> None:
    """Один заход по шагам: двигаемся ли мы вообще и что отвечает игра.

    Ступень 2 дала «мимо» на всех двадцати четырёх парах, а это одинаково
    объясняется и «плита далеко», и «ввод не доходит», и «оценщик слеп».
    Разделять надо числами: свечение до и после шага (сдвинулись ли), доля
    изменившихся пикселей (шли ли вообще) и весь текст полосы HUD после E.
    """
    print("=== диагностика: %s на %.1f с ===" % (клавиша, срок), flush=True)
    f.reset_to_base()
    до_кадр = кадр_после_воскрешения(f)
    до = f.plate_glow(до_кадр)
    print("после респавна: свечение %s" % (до,), flush=True)
    print("путь: %s" % f.shot("det_diag_до"), flush=True)

    f.hand.hold(клавиша, срок)
    time.sleep(0.6)
    после_кадр = f.frame()
    после = f.plate_glow(после_кадр)
    print("после шага:     свечение %s" % (после,), flush=True)
    print("картинка изменилась на %.3f (0 — стояли на месте)"
          % разница(до_кадр, после_кадр), flush=True)
    print("путь: %s" % f.shot("det_diag_после"), flush=True)

    f.hand.interact(1.4)
    time.sleep(0.4)
    кадр = f.frame()
    h, w = кадр.shape[:2]
    x0, y0, x1, y1 = ПОЛОСА
    полоса = кадр[int(y0 * h):int(y1 * h), int(x0 * w):int(x1 * w)]
    текст_полосы = " ".join(t for t, _, _ in ocr.lines(полоса))
    print("полоса HUD после E: %r  оценка %.2f"
          % (текст_полосы, оценка_ответа(текст_полосы)), flush=True)
    print("весь кадр после E:  %r" % ocr.all_text(кадр)[:400], flush=True)
    print("путь: %s" % f.shot("det_diag_после_e"), flush=True)


def main() -> None:
    если_не = "yaw N | route | blind КЛАВИША СЕКУНДЫ N"
    if len(sys.argv) < 2:
        sys.exit("как запускать: python scripts/det_probe.py " + если_не)
    режим = sys.argv[1]
    single.занять("det_probe")
    f = подключиться()
    try:
        if режим == "yaw":
            ступень_рысканье(f, int(sys.argv[2]) if len(sys.argv) > 2 else 10,
                             float(sys.argv[3]) if len(sys.argv) > 3 else 1.5)
        elif режим == "route":
            ступень_маршрут(f)
        elif режим == "diag":
            ступень_диагностика(f, sys.argv[2] if len(sys.argv) > 2 else "a",
                                float(sys.argv[3]) if len(sys.argv) > 3 else 1.5)
        elif режим == "blind":
            if len(sys.argv) < 4:
                sys.exit("blind КЛАВИША СЕКУНДЫ [N]")
            ступень_слепая(f, sys.argv[2], float(sys.argv[3]),
                           int(sys.argv[4]) if len(sys.argv) > 4 else 10)
        else:
            sys.exit("непонятный режим %r: " % режим + если_не)
    finally:
        # Последнее действие ЛЮБОГО опыта: закрыть дверь. Пока база открыта,
        # у нас уносят брейнротов, и цена этому уже измерена.
        f.hand.release_all()
        single.запереть_базу(f)


