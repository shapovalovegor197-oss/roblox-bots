def revive_client() -> bool:
    """Поднять клиент заново и пересобрать фермера на новое окно.

    Без этой проверки бот не замечает пропажи окна и продолжает водить мышью
    по рабочему столу: 31.08 клиент выбило (в игру вошли тем же аккаунтом с
    ноутбука), а цикл ещё минуту слепо тыкал курсором, пока не сработала
    защита pydirectinput от угла экрана. Ввод при этом уходил КУДА УГОДНО.
    """
    global f
    say("окна клиента нет — поднимаю заново")
    try:
        from brainbot.session import Session                # noqa: PLC0415
        from brainbot.mutex import SingletonMutex           # noqa: PLC0415
        SingletonMutex().acquire()
        session = Session(account=s.account(ACCOUNT), settings=s)
        if not session.launch():
            say("клиент не поднялся")
            return False
        win = session.window
    except Exception as exc:                                # noqa: BLE001
        say("поднять клиент не вышло: %s" % exc)
        return False
    f = Farmer(window=win, hand=Hand(win, s.input), tuning=FarmTuning(),
               screens_dir=s.screenshots_dir)
    f.allow_wipe = True
    say("клиент поднят заново, hwnd=%s" % win.hwnd)
    return True


def wait_at_plate() -> None:
    """Досидеть остаток лока и вернуться. НИКУДА не идти.

    Название осталось историческим: раньше здесь бот шёл к плите заранее, чтобы
    запереться в момент истечения. Замеры 03.09 показали, что это делает ХУЖЕ.

    Почему. Надёжный лок начинается с респавна, а респавн и так возвращает на
    спавн, откуда «плита видна сразу» и замок садится за 17-18 с. Значит место,
    где мы досиживаем остаток, не имеет значения вовсе. А слепой подход уводил
    персонажа С этой хорошей точки: при живом локе плита не светится, наводиться
    не на что, и после четырёх шагов вслепую бот оказывался там, откуда её не
    видно ни сверху, ни осмотром.

    Числа (06:40-06:41): подход вслепую -> три дошага «круг не виден» -> «пад не
    опознан» -> «свечения не видно даже осмотром» -> и только потом штатный
    ритуал, который запер за 19.8 с. Дверь простояла открытой 47.1 с. Круги без
    этого подхода в том же прогоне дали 18.8 и 18.2 с.

    Пробовал и промежуточное — доводить по свечению без респавна (dc071fd,
    следом ещё раз): «заперто сразу» не появилось НИ РАЗУ за два прогона.
    """
    left = f.lock_left_now()
    say("досиживаю остаток лока: %d с" % left)
    while f.lock_left_now() > 1:
        time.sleep(0.4)


# Порядок работы, как его сформулировал пользователь: «закрыть — сбор —
# закрыть — сбор — закрыть — закуп — закрыть — продажа». Дверь закрывается
# ПЕРЕД каждым действием, а не раз в круг: пока база открыта, у нас уносят
# брейнротов, и это дороже любой упущенной покупки.
# Цель ночи — семь перерождений, а упирается всё в ОДИН брейнрот с ленты
# (деньги давно есть: 98M при требовании 35M). Поэтому лента идёт через раз,
# а не раз в пять кругов.
# База пуста (всё унесли), собирать и продавать нечего, а деньги на ребёрн
# уже есть — значит смысл только в ленте, где ждём цель. Сбор оставляем
# редким: он же проверяет, не появилось ли что-то на базе.
ДЕЙСТВИЯ = ["лента", "лента", "лента", "сбор"]
СТОИМОСТЬ = {"сбор": 25.0, "лента": 55.0, "продажа": 35.0}


# Сколько заходов на запирание делаем, прежде чем признать круг сорванным.
# Уходить к ленте с открытой дверью нельзя ни при каких обстоятельствах.
LOCK_TRIES = 4
# Дверь открыта дольше этого — кричим в лог отдельной строкой и снимаем кадр.
DOOR_ALARM = 20.0


def учесть_дверь(opened_at: float) -> None:
    """Прибавить к сумме ТОЛЬКО неучтённые секунды открытой двери.

    Раньше сюда шло `время_сейчас - opened_at`, то есть ВСЁ время с истечения
    лока. Но `opened_at` берётся из `_лок_истёк`, а он при неудачном локе не
    двигается: круг заканчивался, начинался следующий, и та же самая минута
    прибавлялась заново. Замер 06.09: прогон длился 3248 с, а сумма показывала
    8648.9 с — больше, чем прошло времени вообще. По такому числу нельзя ни
    судить о ночи, ни сравнивать прогоны, а именно им мы и мерили воровство.
    """
    учтено = max(state.get("_дверь_учтено_до") or opened_at, opened_at)
    теперь = time.time()
    state["дверь_открыта_всего"] = round(
        state.get("дверь_открыта_всего", 0.0) + max(0.0, теперь - учтено), 1)
    state["_дверь_учтено_до"] = теперь


def ensure_locked() -> bool:
    """Дверь закрыта? Если нет — закрыть, и только потом что-то делать.

    ПРАВИЛО ПРОВЕРКИ (02.09, прямое требование пользователя: «ты не закрываешь
    двери — делай себе правило проверки»). Отсюда нельзя выйти с открытой
    дверью молча. Каждый незакрытый заход — строка «ДВЕРЬ ОТКРЫТА N с» и кадр
    в var/screens; суммарное время открытой двери за прогон копится в
    `дверь_открыта_всего` и печатается в каждом круге и в итоговой строке.
    Проверять надо именно эту сумму, а не «вроде работает».

    До 02.09 попытка была ровно одна: `lock_with_retries(attempts=2)` не вышел —
    и круг просто заканчивался, а дверь оставалась открытой до следующего
    круга. В логе 11:05-11:09 так набежало две минуты подряд.
    """
    left = f.lock_left_now()
    if left > 5:
        return True
    if 0 < left <= 40:
        try:
            wait_at_plate()
        except Exception as exc:                            # noqa: BLE001
            say("ожидание у плиты сорвалось: %s" % exc)
    if f.lock_left_now() > 5:
        return True
    t0 = time.time()
    opened_at = state.get("_лок_истёк") or t0
    state["дверь_открыта_с"] = max(0.0, round(t0 - opened_at, 1))
    for заход in range(1, LOCK_TRIES + 1):
        left = f.lock_with_retries(attempts=2)
        открыта = round(max(0.0, time.time() - opened_at), 1)
        if left:
            state["локов"] += 1
            state["локи_секунд"].append(round(time.time() - t0, 1))
            state["_лок_истёк"] = time.time() + left
            state["дверь_открыта_с"] = открыта
            учесть_дверь(opened_at)
            state.setdefault("дверь_открыта_история", []).append(открыта)
            say("ЗАПЕРТО на %d с (за %.1f с), дверь была открыта %.1f с, "
                "всего за прогон %.0f с"
                % (left, time.time() - t0, открыта,
                   state.get("дверь_открыта_всего", 0.0)))
            return True
        state["сбоев"] += 1
        say("ДВЕРЬ ОТКРЫТА %.0f с — лок не вышел (заход %d из %d), пробую снова"
            % (открыта, заход, LOCK_TRIES))
        if открыта >= DOOR_ALARM:
            f.shot("door_open")
        time.sleep(1.5)
    открыта = round(max(0.0, time.time() - opened_at), 1)
    учесть_дверь(opened_at)
    say("ДВЕРЬ НЕ ЗАКРЫЛАСЬ за %.0f с и %d заходов — к ленте НЕ иду, "
        "начинаю круг заново" % (открыта, LOCK_TRIES))
    f.shot("door_stuck")
    return False


def circle() -> None:
    if not client_alive():
        if not revive_client():
            state["сбоев"] += 1
            time.sleep(30)
            return
    if not f.ensure_connected():
        state["сбоев"] += 1
        say("клиент не вернулся в игру")
        time.sleep(30)
        return

    # 1. Дверь. Всегда первым делом — КРОМЕ случая, когда за ней пусто.
    #
    # Проверено 01.09, 04:13: на базе не опознано ни одного брейнрота, подписей
    # Collect ноль. Красть у нас нечего, деньги (98M) не крадутся, а каждый
    # уход с ленты стоит шансов поймать легендарного — цель ребёрна как раз
    # legendary, и такие выпадают редко. Поэтому пока база пуста и мы охотимся,
    # стоим у ленты без перерыва. Как только цель куплена, запираемся сразу:
    # вот её уже унесут.
    need = state["нужно_денег"] or 0
    хватает = bool(state.get("денег_хватает"))
    if need and (state["кэш"] or 0) >= need * 1.05:
        хватает = True
    охота = bool(state["цели"]) and хватает
    # Запираемся ВСЕГДА, пока на базе есть хоть одна цель. Правило пользователя
    # и оно остаётся: 01.09 попытка стоять у ленты после покупки стоила
    # Glorbo Fruttodrillo — взят в 04:21, к 04:30 панель показала его снова
    # тёмным.
    #
    # Но «пусто» теперь не догадка, а ЗАМЕР по окну ребёрна: ярких коробок ноль
    # — на базе нет ни одной цели, и охранять там нечего. Ровно так вышло утром
    # 02.09: за ночь унесли Chef Crabracadabra, обе иконки стали тёмными, а бот
    # продолжал каждые полторы минуты бегать запирать пустую базу и получал
    # семнадцать секунд у ленты из девяноста.
    #
    # Дыру 04:21 закрывает не замок, а немедленный уход: подтверждённая покупка
    # цели ОБРЫВАЕТ стояние у ленты (см. shopping) и следующим же действием
    # ведёт домой запираться.
    # ДВЕРЬ ЗАКРЫВАЕМ ВСЕГДА. Прямое указание пользователя, повторённое 02.09
    # в 11:00 после того, как я попробовал стоять у ленты без замка ради
    # времени. Считать «на базе стоит копейки, потерю переживём» — не моё
    # решение: базу стерегут, точка. Замер «сколько целей на базе» остаётся,
    # но только для отчёта, на запирание он больше не влияет.
    state["база_пуста"] = False
    if not ensure_locked():
        return

    # Цель куплена в прошлом круге — проверяем ребёрн ПОД ЗАМКОМ.
    if state.pop("проверить_ребёрн", False):
        maybe_rebirth(after_target=True)

    # 2. Одно действие — и только если на него хватит запертого времени.
    # Пока охотимся за целью при полном кошельке, всё остальное — трата
    # времени: база пуста, собирать и продавать нечего, а покупать нельзя,
    # ребёрн всё сотрёт. В таком состоянии круг = только лента.
    act = "лента" if охота else ДЕЙСТВИЯ[state["кругов"] % len(ДЕЙСТВИЯ)]
    left = 999.0 if (охота and state.get("база_пуста")) else f.lock_left_now()
    if left < СТОИМОСТЬ[act]:
        # Ждём НЕ НА МЕСТЕ, а стоя на плите. Раньше здесь стоял sleep: бот
        # досиживал остаток лока где придётся, лок истекал, и только потом
        # начиналась дорога к плите — то есть дверь была открыта весь путь.
        # Замер 02.09: 11:16:46 «лока осталось 18 — жду», 11:17:04 лок истёк,
        # заперто в 11:18:08 — дверь простояла открытой 63.9 с при том, что
        # бот всё это время никуда не спешил. wait_at_plate для того и написан.
        say("на «%s» нужно %.0f с, лока осталось %.0f — иду ждать НА ПЛИТУ"
            % (act, СТОИМОСТЬ[act], left))
        state["кругов"] += 1
        try:
            wait_at_plate()
        except Exception as exc:                            # noqa: BLE001
            say("ожидание у плиты сорвалось: %s" % exc)
        return

    before = state["кэш"]
    if act == "сбор":
        # Сперва по подписям «Collect $N» — это прямой признак, где лежат
        # деньги. Не вышло (подписей нет, ушли наружу) — прежний проход по
        # рядам как запасной путь.
        gain = f.collect_by_labels(budget=min(25.0, СТОИМОСТЬ["сбор"]))
        if not gain:
            gain = f.collect_back_from_plate()
        if gain:
            state["собрано_всего"] += gain
            state["сборов_ноль_подряд"] = 0
        else:
            # Ноль на сборе — единственный честный признак, что на базе не
            # осталось ни одного доходного брейнрота (см. планку в
            # worth_buying). Копим его подряд, чтобы одиночный промах прохода
            # не сходил за пустую базу.
            state["сборов_ноль_подряд"] = state.get("сборов_ноль_подряд", 0) + 1
        say("сбор: +%.0f%s" % (gain, "" if gain else " (нулевых подряд %d)"
                               % state.get("сборов_ноль_подряд", 0)))
    elif act == "продажа":
        bar = max(MIN_INCOME, (state["кэш"] or 0) / 20000.0)
        say("продажа: планка дохода %.0f/с" % bar)
        sold = f.sell_below(bar, side=state.get("ряд", -1))
        if sold:
            state["продано"] = state.get("продано", 0) + len(sold)
            state.setdefault("продано_кого", []).extend(sold)
    elif act == "лента":
        walked = goto_belt()
        if walked is None:
            state["сбоев"] += 1
            f.shot("fail_belt")
            say("до ленты не дошёл")
        else:
            # В охоте без лока стоим долго: ограничитель не таймер базы, а
            # собственный счётчик внутри shopping.
            shopping((lambda: 999.0) if (охота and state.get("база_пуста"))
                     else f.lock_left_now)

    note_cash(sane_cash(before) or before)
    maybe_rebirth()
    state["кругов"] += 1
    say("круг %d (%s): покупок %d, ребёрнов %d, кэш %s, дверь открыта за прогон %.0f с"
        % (state["кругов"], act, state["покупок"], state["ребёрнов"], state["кэш"],
           state.get("дверь_открыта_всего", 0.0)))



