def goto_belt(max_steps: int = 8, tries: int = 3) -> float | None:
    """Выйти из базы к ленте и ВСТАТЬ. Возвращает секунды пути.

    Раньше дорога считалась пройденной только когда в кадре появлялся промпт
    «Purchase». Но промпт есть лишь пока рядом едет брейнрот: лента движется,
    и ждать его надо СТОЯ у ленты, а не в пути. Бот же продолжал идти и
    уходил мимо ленты на площадь к Trade Plaza (кадр belt_miss_2 06:40).

    Теперь: встать в известный ноль, отвернуться от базы (проверяя кадром),
    пройти пять шагов наружу — и всё, дальше ждёт закуп.
    """
    t = time.time()
    # Фазы дороги меряем по отдельности. Дорога к ленте — самая дорогая часть
    # круга при запертой двери: замер 02.09 (10:53:38 -> 10:54:29) дал 51 с из
    # 90 секунд лока, и без разбивки не понять, что резать.
    # Фаза «респавн» — это ТРИ разных дела, и сам респавн в ней самый дешёвый:
    # замер 03.09 дал reset_to_base 5.6 с (меню 2.9, подтверждение 2.0,
    # анимация 0.7) при общей фазе 14 с. Остальное — приведение камеры и
    # проверка таблицы игроков. Разделяю, чтобы резать по числу.
    f.reset_to_base()
    _t_r = time.time()
    # 1.2 с, а не 0.4. Срезал её заодно с замером — и получил три захода подряд
    # «доступил по синеве» вместо «на ленте на 3-м шаге» (03.09, 03:12-03:20),
    # после чего зря откатил разворот и паузы камеры, ища виновника не там.
    # Персонаж после возрождения ещё встаёт; камеру приводить по нему рано.
    time.sleep(1.2)
    f.set_work_view()
    _t_v = time.time()
    f.close_players_table()
    say("ПОСЛЕ РЕСПАВНА: сам респавн %.1f, камера %.1f, таблица %.1f"
        % (_t_r - t, _t_v - _t_r, time.time() - _t_v))
    t_респавн = time.time() - t
    # 01.10, приватка: разворот по виду сверху «пеленг на пад + 180» выводит к
    # ленте с любой базы — ручная проба на shapovaluv встала у ленты с ПЕРВОГО
    # шага. Слепые семь оборотов ниже подобраны под одну базу raven и на другой
    # уводят в стену (кадр stuck_respawn 16:47). Они остаются запасным путём,
    # если пад сверху не опознан.
    сверху = f.face_belt_from_top()
    if сверху is not None:
        say("к ленте по виду сверху: %+.1f град" % сверху)
        # Полушаги, а не шаги: лента от спавна в полутора шагах, и целый шаг
        # проскакивал полотно. Цвет ленты НЕ обязателен: в ивентах карта
        # перекрашена (01.10 — вся земля розовая, синевы нет), поэтому число
        # полушагов, замеренное на обычной карте, запоминается для базы
        # аккаунта, и в ивенте бот встаёт по расстоянию и ждёт Purchase.
        запомнено = _полушаги_до_ленты()
        for i in range(max_steps * 2):
            f.hand.hold("w", 0.3)
            time.sleep(0.3)
            prompt, inside = belt_signals()
            if prompt:
                return _пришли_сверху(t, i + 1, "промпт")
            if on_belt() and not inside:
                _запомнить_полушаги(i + 1)
                return _пришли_сверху(t, i + 1, "полотно под ногами")
            if inside:
                say("ушёл внутрь базы на %d-м полушаге — разворачиваюсь заново" % (i + 1))
                if f.face_belt_from_top() is None:
                    break
                continue
            if i + 1 >= запомнено and not nav.find_conveyor(f.frame()):
                # Синевы в кадре нет вовсе — это ивент, а не промах.
                return _пришли_сверху(t, i + 1, "по расстоянию, %d полушагов" % запомнено)
            подрулить_на_ленту()
        if step_onto_belt():
            prompt, inside = belt_signals()
            if prompt or (on_belt() and not inside):
                return _пришли_сверху(t, max_steps, "доступил стрейфом")
        f.shot("belt_top_miss")
        say("по виду сверху ленту не взял — пробую прежний путь")
        f.reset_to_base()
        time.sleep(1.2)
        f.set_work_view()
        t_респавн = time.time() - t
    if f.face_base_from_top() is None:
        say("пад сверху не опознан — известного нуля нет")
    t_пеленг = time.time() - t - t_респавн
    # Разворот наружу — вторая по дороговизне фаза: 19.2 с в круге 1 против
    # 6.5 в круге 3. Дорого потому, что на каждом обороте гоняются ДВА полных
    # OCR, и если условие не сходится, бот крутит все семь оборотов (315 град)
    # и уходит наугад. Печатаем, что именно видно, иначе чинить нечего.
    # Смотрим кадром только на первых двух оборотах. Днём подписи мира читаются
    # сразу (замер 02.09: разворот 6.5 с — два оборота и выход), а ночью не
    # читаются вовсе: 19:46 дал «вижу мир False» семь раз из семи, цикл всё равно
    # докрутил до конца, и распознавание стоило 19.7 с из 90 секунд лока.
    # Само движение не трогаю: семь оборотов по 45 — это те самые слепые 315,
    # после которых бот четырежды подряд вставал на ленту с третьего шага.
    # Одним движением на 180 уже пробовали (fb6b49f) — на ленту не попадал,
    # доходил «по синеве» за 45 с, и правку откатили.
    # Семь оборотов по 45 — и НЕ одним движением. Пробовал досылать остаток
    # одной протяжкой на 225 (угол тот же, 45+45+225 = 315): дважды из двух
    # заходов бот терял ленту и добирался «по синеве» (03.09, 03:12:53 и
    # 03:14:15), тогда как дроблёным разворотом выходил «на ленте на 3-м шаге»
    # круг за кругом. То есть дробление — часть механики, а не лишние паузы:
    # игра успевает доворачивать между кусками. Второй раз наступаю на те же
    # грабли, что и fb6b49f; больше сюда не лезу.
    #
    # Кадром смотрим только на первых двух оборотах: днём выход как раз там,
    # ночью подписи мира не читаются вовсе и платить за распознавание не за что.
    for _об in range(7):
        if _об < 2:
            # Одно распознавание на оборот, не два. `scene_flags` гоняет свой
            # OCR, и вызов его рядом с этим стоил бы вдвое: замер 02.09 дал
            # 19.7 с разворота из 90 секунд лока. Флаги считаем из тех же строк.
            _кадр = f.frame()
            _мир = " ".join(t.lower() for t, x, _y in ocr.lines(_кадр)
                            if x / _кадр.shape[1] > 0.18)
            внутри = "allow" in _мир or "lock base" in _мир or "lockbase" in _мир
            наружу = any(m in _мир for m in f.OUTSIDE_MARKERS)
            if not внутри and наружу:
                # Обрыв не логировался вовсе, и по журналу нельзя было понять,
                # сколько градусов бот в итоге отвернул. Ночь 12.09: из 77
                # заходов 14 оборвались здесь на 0 град и 44 на 45 град вместо
                # положенных 315 — а решает это ОДИН маркер внешнего мира,
                # который читается и из собственной базы (вывески соседей).
                say("разворот оборван на %d град: маркеры мира %s"
                    % (_об * 45, [m for m in f.OUTSIDE_MARKERS if m in _мир]))
                break
            say("разворот %d: внутри базы %s, вижу мир %s" % (_об + 1, внутри, наружу))
        f.hand.turn_degrees(45)
        time.sleep(0.35)
    t_разворот = time.time() - t - t_респавн - t_пеленг
    min_blue_steps = 3

    def пришли(шаг: int, как: str):
        say("на ленте на %s-м шаге (%s); ДОРОГА: респавн %.1f, пеленг %.1f, "
            "разворот %.1f, шаги %.1f, всего %.1f"
            % (шаг, как, t_респавн, t_пеленг, t_разворот,
               time.time() - t - t_респавн - t_пеленг - t_разворот,
               time.time() - t))
        f.shot("belt_stand")
        return time.time() - t

    # Приход к ленте НЕЛЬЗЯ проверять одним живым Purchase.
    #
    # Промпт горит, только пока мимо едет брейнрот, — то есть проверка отвечает
    # «да» по удаче, а не по месту. Замер ночи 12.09: 77 заходов, приход
    # засчитан 2 раза (2.6%), при том что на 75 кадрах `belt_stand_miss` лента
    # в кадре есть всегда, а бот стоит РЯДОМ с ней, на траве справа: центр
    # полотна на x=0.22-0.27 кадра, синевы под ногами 0.09-0.16. Для сравнения,
    # в рабочие дни (до 11.09) кадры `belt_stand` дают центр 0.50 и синеву 0.97
    # — бот стоял НА полотне. За 111 кругов ночи — ноль покупок.
    #
    # Пропал ровно один шаг: 11.09 вместе с ложным `on_belt()` из пути убрали и
    # `step_onto_belt()` — доступание на полотно стрейфом. Ложное срабатывание
    # у ворот базы оно не чинило (его чинит проверка «внутри базы»), а последние
    # два-три шага вбок закрывало только оно.
    for i in range(max_steps):
        f.hand.hold("w", 0.6)
        time.sleep(0.22)
        # Третий шаг — измеренная точка ожидания на синей дороге. Пятый и
        # последующие уводят мимо ленты к боковой стене своей базы.
        if i + 1 < min_blue_steps:
            continue
        prompt, inside = belt_signals()
        if prompt:
            return пришли(i + 1, "промпт")
        # Синий пол есть и у ворот базы. Ночной кадр 11.09 доказал, что голая
        # синева под ногами объявляла лентой площадку у стены, после чего бот
        # простоял там восемь часов. Отличаем по подписи «Lock Base» в кадре:
        # у ворот она видна, на полотне — нет.
        if on_belt() and not inside:
            return пришли(i + 1, "полотно под ногами")
        if inside:
            break
    # Рядом, но не на полотне — доступаем стрейфом по картинке.
    if step_onto_belt():
        prompt, inside = belt_signals()
        if prompt or (on_belt() and not inside):
            return пришли(max_steps, "доступил стрейфом")
    f.shot("belt_stand_miss")
    say("слепой путь не дал ленту — запускаю обучение дороги по секторам")
    route = f.aim_belt()
    if route:
        f.save_belt_route(route)
        say("ЛЕНТА ПОДТВЕРЖДЕНА Purchase; маршрут выучен: поворот %s, вперёд %.1f с"
            % (route["поворот"], route["вперёд"]))
        f.shot("belt_stand_verified")
        return time.time() - t
    say("ленту не нашёл даже обучением — успех не засчитываю")
    return None


def worth_buying(item, price) -> tuple[bool, str]:
    """Брать ли. Цели — всегда; остальных — только если быстро окупятся."""
    if item is None:
        return False, "неизвестный"
    # В непрерывной охоте известна ровно одна отсутствующая цель. Не покупаем
    # повтор уже выполненного требования из накопленного списка прошлых чтений.
    if state.get("режим_одной_цели") and state.get("цель_охоты"):
        want = {normalize(state["цель_охоты"])}
    else:
        want = {normalize(n) for n in state["цели"]}
    if normalize(item.name) in want:
        return True, "ЦЕЛЬ"
    # НЕ проедать порог перерождения. Цель прогона — цепочка ребёрнов, а для
    # каждого нужны деньги ($12.5M на первом). Доходные брейнроты стоят
    # миллионы: два подряд увели кэш с 35.4 до 24.9, и ещё пара оставила бы
    # бота без ребёрна. Держим требование плюс четверть сверху.
    # ТОЛЬКО ЦЕЛИ. Обычные покупки сейчас не дают ничего: доход с брейнротов
    # снимается сбором, а сбор сломан (пады видны, наступание не
    # засчитывается). Значит доходный брейнрот — это минус деньги и минус
    # слот, а слотов восемь, и забитые слоты мешают взять цель. Ребёрн базу
    # всё равно стирает. Вернуть обычный закуп, когда починится сбор.
    if ONLY_TARGETS:
        return False, "беру только цели"
    # Денег на ребёрн уже хватает — НИЧЕГО не покупаем, кроме цели.
    # Перерождение стирает и деньги, и брейнротов: 98 миллионов, вложенные
    # сейчас в доходных, сгорят вместе с ними через полчаса. Ждём цель.
    need = state["нужно_денег"] or 0
    if need and (state["кэш"] or 0) >= need * 1.05 and state["цели"]:
        return False, "денег на ребёрн хватает, коплю на цель"
    # Порог ребёрна бережём, ТОЛЬКО когда он уже взят. Иначе правило душит
    # само себя: 31.08 требование выросло до $35M, кэш был $1.32M, и условие
    # «после покупки должно остаться 35 миллионов» отменяло КАЖДУЮ покупку —
    # бот перестал зарабатывать вовсе, кэш стоял намертво четыре круга.
    #
    # Логика простая: денег меньше требования — растём покупками по
    # окупаемости, это единственный способ до него добраться. Денег больше —
    # не опускаемся обратно.
    need = state["нужно_денег"] or 0
    cash = state["кэш"] or 0
    if need and price and cash >= need * 1.25 and cash - price < need * 1.25:
        return False, "не проедаю порог ребёрна"
    income = item.base_income or 0
    # Планка дохода РАСТЁТ вместе с кэшем — лестница на уровне покупки.
    # Слотов восемь, и брейнрот за 3 доллара в секунду занимает место, которое
    # завтра стоило бы отдать под тысячи. Замер 31.08: с плоской планкой бот
    # за два круга купил двенадцать штук по 3-35/с (одного и того же трижды),
    # суммарный доход около сотни в секунду — против требования в 35 миллионов
    # это ничто.
    #
    # cash/20000: при 600 тысячах берём от 30/с, при 5 миллионах — от 250/с,
    # при 35 миллионах — от 1750/с.
    #
    # У лестницы есть провал, и ночь 05.09 в него провалилась целиком. Кэш
    # $68.22M даёт планку $3411/с, а база при этом ПУСТАЯ: купленного в 01:41
    # Lerulerulerule ($8750/с) унесли, три прохода сбора подряд дали ровно
    # ноль, деньги замерли на месте. Легендарные с ленты ($750/с) под планку не
    # проходят, мифические попадаются раз в час — то есть бот сидел с полным
    # кошельком, пустой базой и НУЛЕВЫМ доходом, а до порога ребёрна не хватало
    # $32M, которые взять неоткуда.
    #
    # Поэтому планка привязывается не только к кошельку: пока сбор подряд даёт
    # ноль, на базе зарабатывать некому, и любой доход лучше никакого. Как
    # только сбор снова приносит деньги, лестница возвращается — счётчик
    # обнуляется в тот же момент.
    #
    # Планка пустой базы — 500/с, а не MIN_INCOME. Слотов восемь, и забить их
    # эпиками по 100/с значит закрыть место под легендарных: ровно так 31.08
    # бот за два круга купил двенадцать штук по 3-35/с. С 500/с проходят
    # легендарные ($750/с, на ленте они частые) — восемь таких дают $6K/с, то
    # есть недостающие до порога $32M за полтора часа.
    floor = max(MIN_INCOME,
                min((state["кэш"] or 0) / 20000.0, INCOME_FLOOR_CAP))
    if state.get("сборов_ноль_подряд", 0) >= 2:
        floor = max(MIN_INCOME, ПЛАНКА_ПУСТОЙ_БАЗЫ)
    if income < floor:
        return False, "доход %s меньше планки %.0f" % (income, floor)
    # Пока копим до известного денежного порога, повтор дорогого доходного
    # существа полезнее пустого слота. Это заодно восстанавливает доход после
    # кражи: список наших покупок помнит имя, но украденного на базе уже нет.
    # Для дешёвых существ прежний запрет дублей остаётся, а при полном кошельке
    # выше уже срабатывает режим «только цель».
    if (item.name in state["куплено"]
            and not (need and cash < need and income >= INCOME_FLOOR_CAP)):
        return False, "такой уже есть"
    if price and income and price / income > PAYBACK_SEC:
        return False, "окупается %.0f с" % (price / income)
    return True, "доход %s/с" % income


def reserve_now() -> float:
    """Сколько секунд оставить на дорогу домой и запирание.

    Берём медиану замеренных локов и добавляем шесть секунд. Пока замеров нет,
    считаем по последнему известному времени — 45 секунд.
    """
    times = sorted(state["локи_секунд"][-5:])
    if not times:
        return 45.0
    mid = times[len(times) // 2]
    return max(RESERVE_MIN, mid + 6.0)


def shopping(deadline_left, continuous: bool = False) -> None:
    """Стоять у ленты и покупать до таймера лока либо до конца охоты."""
    f.hand.move(13, 65)          # курсор в угол, чтобы не закрывал надписи
    f.shot("belt_shop")          # что именно перед носом, когда начали закуп
    cash = sane_cash(state["кэш"]) or state["кэш"]
    note_cash(cash)
    if state["кэш_старт"] is None:
        state["кэш_старт"] = cash
    # Стоим у ленты ФИКСИРОВАННОЕ время, а не «пока горит лок».
    #
    # Расчёт был такой: лок 80 с, дорога домой и запирание 35 — значит уходить
    # надо заранее. Но лок сам занимает 31 с, дорога к ленте ещё 25-40, и на
    # закуп оставалось 3 секунды: за пять кругов бот не прочитал ни одной
    # карточки. А цель прогона — два именных брейнрота для ребёрна, и ребёрн
    # всё равно СТИРАЕТ базу: стеречь на ней нечего, а не купить цель — значит
    # не сделать ни одного перерождения.
    t_belt = time.time()
    last_seen = [time.time(), 0]        # когда видели карточку, сколько сняли idle-кадров
    last_status = time.time()
    # Уходим, пока лок ЕЩЁ ДЕРЖИТ. Требование пользователя: дверь должна быть
    # закрыта, у нас воруют почти всё. Дорога домой и запирание занимают около
    # сорока секунд, поэтому при остатке меньше HOME_RESERVE закуп прекращаем,
    # сколько бы времени ни оставалось от BELT_STAY.
    # Запас на возврат зависит от того, ЕСТЬ ЛИ ЧТО ОХРАНЯТЬ. Пока на базе нет
    # ни одной цели, красть у нас нечего, и лишние секунды лучше отдать ленте:
    # мы ловим редкого легендарного, и каждая карточка на счету. Как только
    # цель куплена — уходим раньше и запираемся плотнее.
    # Замер 02.09, вечер: запас в 45 с не покупал НИЧЕГО. Дверь всё равно
    # стояла открытой 17.1 / 25.9 / 24.5 с за круг, потому что wait_at_plate
    # доходит до плиты вслепую и в двух случаях из трёх не подтверждает лок —
    # дальше всё равно идёт полный ритуал с респавном (21 с). А ленте при этом
    # доставалось 7-15 секунд из 90, карточек прочитано НОЛЬ.
    # Дорога до плиты честно стоит: респавн 14-16, пеленг 6.5, четыре шага 3.
    # Отсюда 25 — это приезд ровно к истечению, а не раньше.
    # Запас на возврат почти обнулён, и это то же открытие, что и в
    # wait_at_plate: уходить с ленты ЗАРАНЕЕ не покупает ничего. Запирание
    # начинается с респавна, а респавн телепортирует на спавн откуда угодно —
    # значит место, где нас застало истечение, не влияет ни на что. Замер
    # 03.09, 06:50-06:57: дверь 16.9 / 16.0 / 16.8 / 17.8 / 18.8 с за круг,
    # ровно стоимость ритуала, и она одинакова хоть с ленты, хоть от плиты.
    #
    # Зачем: цель уносят за 30-40 минут (Chef куплен 06:42, украден к 07:22), а
    # вторая цель за это время не успевает выпасть. Лента получала 30 с из 107
    # секунд цикла; теперь получит около 55, то есть шанс поймать вторую цель
    # внутри окна кражи почти удваивается.
    #
    # Откат, если дверь_открыта_с за круг вырастет заметно выше 20 с.
    reserve = 5.0
    # При единственной цели и готовой сумме остаёмся здесь до конца всего
    # прогона. Выход произойдёт раньше сам, как только цель будет куплена.
    # Обычный круг по-прежнему ограничен коротким окном лока.
    if continuous:
        стоять = max(0.0, globals().get("end", time.time() + BELT_STAY_HUNT) - t_belt)
    else:
        стоять = BELT_STAY
    # `read_card` специально опрашивает один промпт много раз, чтобы не
    # пропустить цель на движущейся ленте. В статистике это должен быть один
    # проезд, а не десятки «брейнротов». Сбрасываем защёлку, когда промпт
    # исчезает, либо когда имя сменилось прямо в следующем кадре.
    counted_item = None
    while time.time() - t_belt < стоять and deadline_left() > reserve:
        if continuous and time.time() - last_status >= 30:
            state["на_ленте_с"] = round(time.time() - t_belt, 1)
            save()
            last_status = time.time()
            if not client_alive():
                raise RuntimeError("клиент пропал во время непрерывной охоты")
        card = f.read_card()
        if not card["ready"]:
            counted_item = None
            # Промпта нет между брейнротами. Позицию не меняем: живые прогоны
            # показали, что дополнительные W уводят с ленты к боковой стене.
            # Раз в 15 секунд сохраняем кадр, чтобы отличить пустой промежуток
            # от неверной позиции без вмешательства в маршрут.
            time.sleep(0.2)
            if time.time() - last_seen[0] > 15 and last_seen[1] < 3:
                f.shot("belt_idle")
                last_seen[0] = time.time()
                last_seen[1] += 1
                say("у ленты пусто 15 с — остаюсь на месте, кадр %d из 3"
                    % last_seen[1])
            continue
        last_seen[0] = time.time()
        item = card.get("item")
        if item is None:
            say("карточка: имя не опознано, цена %s" % card.get("price"))
        if item is not None and item.name != counted_item:
            state["лента_видела"][item.name] = state["лента_видела"].get(item.name, 0) + 1
            counted_item = item.name
        take, why = worth_buying(item, card.get("price"))
        if not take:
            time.sleep(0.3)
            continue
        if DRY_RUN:
            say("ПРОБА: купил бы %s (%s), ввода E не будет" % (item.name, why))
            time.sleep(0.3)
            continue
        name = item.name
        if why == "ЦЕЛЬ":
            state["цели_видел"] += 1
            say("ЦЕЛЬ НА ЛЕНТЕ: %s, цена %s — беру" % (name, card.get("price")))
            # ЦЕЛЬ проверяем НЕ ПО ДЕНЬГАМ. HUD округляет до трёх значащих:
            # при кэше $25.44M покупка за $20K не меняет ни одной цифры, и
            # проверка «деньги упали» всегда отвечает «не взялась». Именно так
            # 04:45 бот решил, что не купил Trulimero Trulicina, и полез
            # освобождать слот. Верный признак — брейнрот на базе, а его
            # сверяет сам ребёрн.
            # Жмём и ПРОВЕРЯЕМ, что взялось, а не «второй раз не повредит».
            # 01.09 в 05:59 бот отчитался «ЦЕЛЬ Glorbo Fruttodrillo: взял», а
            # окно ребёрна через минуту показало его тёмным: покупка не прошла
            # вовсе. Признак взятия — карточка сменилась: купленный уезжает с
            # ленты, и промпт либо гаснет, либо называет уже другого.
            # Чем проверять — зависит от цены. HUD показывает три значащие
            # цифры, то есть при $98.7M его шаг — сто тысяч. Легендарный с
            # ленты стоит от $200K, такую покупку видно; дешёвого не видно
            # никак, и там остаётся только «карточка сменилась». Но лента
            # ЕДЕТ, и смена карточки сама по себе — слабый признак: товар мог
            # просто уехать. Поэтому сильный признак берём, когда он доступен.
            цена = card.get("price") or 0
            шаг_hud = 10 ** (len(str(int(cash or 1))) - 3) if cash else 0
            деньгами = bool(цена and шаг_hud and цена >= шаг_hud)
            взял = False
            уехал = False        # товар ушёл с ленты — слоты тут ни при чём
            for попытка in range(1, 4):
                f.hand.interact(BUY_HOLD)
                time.sleep(0.8)
                после = sane_cash(cash)
                упал = (после is not None and cash is not None
                        and после < cash - шаг_hud / 2.0)
                снова = f.read_card()
                ушёл = (not снова["ready"] or (снова.get("name") or "") != name)
                if упал or (ушёл and not деньгами):
                    взял = True
                    say("ЦЕЛЬ %s взята с попытки %d (%s)"
                        % (name, попытка,
                           "деньги упали" if упал else "карточка сменилась"))
                    if после is not None:
                        cash = после
                    break
                if ушёл and деньгами:
                    # Товар уехал с ленты, а деньги на месте — не купили.
                    say("ЦЕЛЬ %s уехала с ленты, деньги не тронуты" % name)
                    уехал = True
                    break
                say("ЦЕЛЬ %s: попытка %d не взялась, карточка на месте"
                    % (name, попытка))
            if not взял and уехал:
                # Освобождать слот НЕ НАДО: покупать уже нечего, товар уехал.
                # Замер 05.09, 01:30-01:31: после «уехала» бот шёл продавать,
                # а продажа начинается с to_reference() — то есть с респавна.
                # Респавн уносит с ленты домой, кадр target_miss снят стоящим
                # на COLLECT ZONE, и дальше цикл читал карточки, стоя в базе.
                # Ждём следующую карточку на месте.
                say("ЦЕЛЬ %s уехала — жду следующую карточку" % name)
                continue
            if not взял:
                # Карточка на месте, а покупка не идёт — вот это уже похоже на
                # забитые слоты. Освобождаем худшего и пробуем ещё раз: цель
                # важнее содержимого базы, ребёрн его всё равно сотрёт.
                try:
                    продан = f.sell_weakest()
                    if продан:
                        say("продан %s ради цели" % продан)
                        f.hand.interact(BUY_HOLD + 0.8)
                        time.sleep(0.6)
                        снова = f.read_card()
                        взял = (not снова["ready"]
                                or (снова.get("name") or "") != name)
                except Exception as exc:                    # noqa: BLE001
                    say("продать не вышло: %s" % exc)
                if not взял:
                    # sell_weakest ходил через to_reference(), значит мы дома,
                    # а не у ленты. Дальше читать карточки бессмысленно —
                    # заканчиваем закуп, круг сам запрётся и вернётся сюда.
                    say("ЦЕЛЬ %s НЕ взята, стою дома после продажи — "
                        "закрываю закуп" % name)
                    f.shot("target_miss")
                    return
            state["цели_куплены"].append(name)
            # На базе появилась цель. При обычной охоте сначала запираемся; при
            # режиме единственной цели caller сразу откроет окно ребёрна —
            # отдельный поход к воротам лишь увеличил бы время до обнуления.
            state["база_пуста"] = False
            state["держим_цель"] = True
            state["проверить_ребёрн"] = True
            say("ЦЕЛЬ %s: взял, %s"
                % (name, "сразу иду на ребёрн" if continuous
                   else "ухожу запираться"))
            cash = sane_cash(cash) or cash
            note_cash(cash)
            # Закуп обрываем сразу: дальше либо замок, либо немедленный ребёрн.
            return
        f.hand.interact(BUY_HOLD)
        time.sleep(0.5)
        now = sane_cash(cash)
        if now is not None and cash is not None and now < cash - 1:
            state["покупок"] += 1
            state["куплено"].append(name)
            if normalize(name) in {normalize(n) for n in state["цели"]}:
                state["цели_куплены"].append(name)
                say("!!! КУПЛЕНА ЦЕЛЬ %s за %.0f" % (name, cash - now))
            else:
                say("куплено %s (%s): %.0f -> %.0f" % (name, why, cash, now))
        elif why == "ЦЕЛЬ":
            # Цель не купилась — самая вероятная причина не промах по клавише,
            # а ЗАБИТЫЕ СЛОТЫ: за круг бот берёт три-четыре штуки, и восьмой
            # слот кончается быстро. Освобождаем место худшим по доходу и
            # пробуем снова: цель важнее любого содержимого базы, потому что
            # ребёрн базу всё равно сотрёт.
            say("ЦЕЛЬ %s не взялась — освобождаю слот" % name)
            try:
                sold = f.sell_weakest()
                if sold:
                    say("продан %s ради цели" % sold)
            except Exception as exc:                        # noqa: BLE001
                say("продать не вышло: %s" % exc)
            f.hand.interact(BUY_HOLD + 0.8)
            time.sleep(0.6)
            now = sane_cash(cash)
            if now is not None and cash is not None and now < cash - 1:
                state["покупок"] += 1
                state["куплено"].append(name)
                state["цели_куплены"].append(name)
                say("!!! КУПЛЕНА ЦЕЛЬ %s со второго раза" % name)
        if now is not None:
            cash = now
            note_cash(now)
    save()


