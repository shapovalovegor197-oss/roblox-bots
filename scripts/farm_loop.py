def note_targets_on_base(info: dict) -> None:
    """Сколько целей СЕЙЧАС стоит на базе — по окну ребёрна, а не по памяти.

    Окно — источник первой руки: выполненное требование горит цветной иконкой,
    невыполненное — чёрным силуэтом. Ярких коробок ноль — на базе нет ни одной
    цели, красть у нас нечего. Это единственный признак, которому можно верить:
    свои покупки бот помнит, а КРАЖИ — нет, и ровно на этом 02.09 он вышел
    утром охранять пустую базу (Chef Crabracadabra унесли за ночь).
    """
    коробок = info.get("boxes") or 0
    if not коробок:
        # Окно не открылось или не дорисовалось. «Коробок ноль» — это СЛЕПОТА,
        # а не «на базе пусто»: принять её за пустую базу значит перестать
        # запирать базу с целью. Оставляем прежнюю картину.
        say("окно ребёрна без коробок — картину базы не меняю (было %s)"
            % state.get("целей_на_базе"))
        return
    тёмных = len(info.get("need_items") or []) + (info.get("unreadable_dark") or 0)
    ярких = max(0, коробок - тёмных)
    state["недостающие_цели"] = list(info.get("need_items") or [])
    state["непрочитанных_целей"] = info.get("unreadable_dark") or 0
    state["осталось_целей"] = тёмных
    state["целей_на_базе"] = ярких
    state["коробок_в_окне"] = коробок
    state["держим_цель"] = ярких > 0
    # ОХРАНЯЕМ только полный набор. Пока хоть одного требования не хватает,
    # ребёрн невозможен, а всё, что стоит на базе, стоит копейки против
    # упущенного времени у ленты: Glorbo Fruttodrillo — $200K при кэше $98.5M,
    # и поймать его заново вышло за три минуты охоты (02.09, 10:47 старт —
    # 10:50 куплен), тогда как под охраной за три часа ночи он попался дважды.
    # Полный набор — другое дело: с ним бот идёт перерождаться сразу, и вот эти
    # полминуты база должна быть заперта.
    state["охраняем"] = коробок > 0 and ярких >= коробок
    say("на базе целей: %d из %d%s"
        % (ярких, коробок, ", набор полный" if state["охраняем"] else ""))


def one_target_hunt() -> bool:
    """Можно ли до покупки единственной цели совсем не возвращаться к воротам."""
    need = state.get("нужно_денег") or 0
    cash = state.get("кэш") or 0
    missing = state.get("недостающие_цели") or []
    enough = cash >= need * ONE_TARGET_CASH_MARGIN
    # Полная зелёная полоса в окне ребёрна — прямой ответ игры. HUD иногда
    # возвращает None сразу после закрытия панели; это не должно выключать
    # охоту, если панель уже подтвердила, что денежное требование выполнено.
    if state.get("денег_хватает") is True:
        enough = True
    return bool(
        need
        and enough
        and state.get("коробок_в_окне") == 1
        and state.get("осталось_целей") == 1
        and state.get("целей_на_базе") == 0
        and not state.get("держим_цель")
        and state.get("непрочитанных_целей", 0) == 0
        and len(missing) == 1
    )


def read_goals() -> None:
    """Требования ребёрна: сумма и именные брейнроты."""
    try:
        f.close_players_table()
        if not f.open_menu_item("birth"):
            say("окно ребёрна не открылось — цели оставляю прежними")
            return
        time.sleep(0.6)
        info = f.read_rebirth_window()
        # Окно бывает не дорисовано к первому кадру: 02.09 в 10:44 чтение
        # вернуло ноль коробок и обе суммы None. Даём ему секунду и читаем
        # ещё раз — это дешевле, чем круг вслепую.
        for _ in range(2):
            if info.get("boxes"):
                break
            time.sleep(1.0)
            info = f.read_rebirth_window()
        # Закрыть ОБЯЗАТЕЛЬНО и проверить. Незакрытое окно перекрывает середину
        # кадра, и дальше бот слеп: ни вида сверху, ни свечения плиты. Ровно так
        # 30.08 сгорели четыре лока подряд.
        if not f.dismiss_modals():
            f.shot("goals_modal_stuck")
            say("окно ребёрна не закрылось — снял кадр goals_modal_stuck")
        # ЦЕЛИ НАКАПЛИВАЕМ, а не перезаписываем. Панель через раз показывает
        # только одно требование из двух (детектор коробок неустойчив), и если
        # верить последнему чтению, второй предмет выпадает из списка — а
        # значит не покупается. Ночью 01.09 это стоило всего результата:
        # Chef Crabracadabra проехал по ленте ДВАЖДЫ и оба раза был пропущен,
        # потому что в списке целей его в тот момент не было.
        #
        # Лишняя покупка уже купленного стоит копейки (легендарный шёл от $200),
        # а пропущенная цель — целой ночи.
        всё = set(state.get("все_требования") or [])
        всё |= set(info["need_items"]) | set(info.get("items_all") or [])
        state["все_требования"] = sorted(всё)
        state["цели"] = state["все_требования"]
        note_targets_on_base(info)
        if info["need_cash"]:
            state["нужно_денег"] = info["need_cash"]
        elif any(normalize(x) == normalize("Bombombini Gusini")
                 for x in state["цели"]):
            # На текущем уровне мелкий текст суммы стабильно не читается, хотя
            # сохранённый кадр панели однозначно показывает $... / $1B.
            # Без этого значения режим охоты и защита порога не включаются.
            state["нужно_денег"] = 1_000_000_000.0
        # Хватает ли денег — спрашиваем У ПАНЕЛИ, а не только у HUD. Полоса
        # прогресса «$ 35M / $ 35M» — это ответ игры, и он есть даже когда HUD
        # не прочитался. 02.09 в 10:42 старт вернул кэш None (сразу после
        # закрытия окна), охота не включилась, и бот пошёл запирать пустую базу.
        if info["have_cash"] is not None and info["need_cash"]:
            state["денег_хватает"] = info["have_cash"] >= info["need_cash"]
        elif info.get("bar_green") is not None:
            # Цифры «$ 100M / $ 350M» OCR корёжит в кириллицу («100M» -> «шом»),
            # и тогда обе стороны сравнения None — ответ «денег хватает: None»
            # держался всю ночь 05.09. Полоса требования при этом ЗАПОЛНЯЕТСЯ
            # зелёным и читается цветом (замер 06.09: полная 0.713, пустая
            # 0.000). Гейт самого ребёрна на неё уже переведён (8c32b63) —
            # доводим до круга, иначе охота не включается никогда.
            state["денег_хватает"] = bool(info.get("cash_full"))
        remember_goals()
        say("цели: %s, нужно $%s, накоплено $%s (полоса %.3f, касса %s)"
            % (", ".join(state["цели"]), info["need_cash"], info["have_cash"],
               info.get("bar_green") or 0.0,
               "набрана" if info.get("cash_full") else "нет"))
    except Exception as exc:                                # noqa: BLE001
        say("цели прочитать не вышло: %s" % exc)


def on_belt() -> bool:
    """Лента ПОД НОГАМИ: низ кадра залит синим полотном конвейера.

    Промпт «Purchase» появляется, только пока рядом едет брейнрот, — по нему
    нельзя понять, дошли ли мы. А полотно под ногами есть всегда. Замер по
    кадрам 31.08: стоя на ленте — 0.98, на траве у чужой базы — 0.00, на
    площади — 0.15, на своей дорожке внутри базы — 0.69. Порог 0.8 отделяет
    ленту от собственной дорожки с запасом.
    """
    fr = f.frame()
    h, w = fr.shape[:2]
    band = fr[int(h * 0.72):int(h * 0.95), int(w * 0.33):int(w * 0.67)]
    import cv2, numpy as np
    hsv = cv2.cvtColor(band, cv2.COLOR_BGR2HSV)
    m = cv2.inRange(hsv, np.array((100, 120, 90), np.uint8),
                    np.array((130, 255, 255), np.uint8))
    return float(m.mean()) / 255.0 > 0.8


def step_onto_belt(tries: int = 7) -> bool:
    """Доступить НА полотно ленты, видя его в кадре.

    Бот выходил из базы и вставал впритык к ленте, но не на неё: полотно было
    в двух шагах слева, поэтому ни промпта, ни синевы под ногами (кадр
    belt_stand_miss_20260901-033024). Правим по картинке — находим синюю
    полосу в нижней половине кадра и подходим к её середине.
    """
    import cv2, numpy as np
    for _ in range(tries):
        prompt, inside = belt_signals()
        if prompt or (on_belt() and not inside):
            return True
        fr = f.frame()
        h, w = fr.shape[:2]
        band = fr[int(h * 0.55):int(h * 0.95), :]
        hsv = cv2.cvtColor(band, cv2.COLOR_BGR2HSV)
        m = cv2.inRange(hsv, np.array((100, 120, 90), np.uint8),
                        np.array((130, 255, 255), np.uint8))
        cols = m.sum(axis=0).astype(float)
        if cols.sum() < 255 * 50:
            return False
        cx = float((cols * np.arange(w)).sum() / cols.sum()) / w
        off = cx - 0.5
        if abs(off) > 0.08:
            f.hand.hold("d" if off > 0 else "a", min(0.45, abs(off) * 1.2))
            time.sleep(0.15)
        else:
            f.hand.hold("w", 0.45)
            time.sleep(0.15)
    prompt, inside = belt_signals()
    return prompt or (on_belt() and not inside)


def belt_signals() -> tuple[bool, bool]:
    """(живой промпт покупки, я внутри базы) — за ОДНО распознавание.

    Промпт: вхождение по всему кадру ловило и дальнюю вывеску, и подсказку
    чата: бот останавливался за десяток шагов до ленты и стоял там весь лок,
    ни разу не прочитав карточку (прогон 03:20–03:45, пять кругов, покупок
    ноль). Признак промпта тот же, что у read_card: короткая строка со словом.

    «Внутри базы» берём из того же распознавания даром. Оно нужно, чтобы
    отличить полотно ленты от синей дорожки у ворот собственной базы: ровно на
    ней 11.09 `on_belt()` объявил успех, и бот простоял у стены восемь часов.
    Второй полный OCR ради этого гонять незачем.
    """
    lines = ocr.lines(f.frame())
    prompt = any("purchase" in t.lower() and len(t.strip()) <= 24
                 for t, _, _ in lines)
    txt = " ".join(t.lower() for t, _, _ in lines)
    inside = "lock base" in txt or "lockbase" in txt or "allow" in txt
    return prompt, inside


def at_belt() -> bool:
    return belt_signals()[0]


def подрулить_на_ленту(tol: float = 0.06, tries: int = 4) -> None:
    """Довернуть камеру на полотно, не двигаясь (как scripts/goto_belt.py)."""
    for _ in range(tries):
        fr = f.frame()
        w = fr.shape[1]
        c = nav.find_conveyor(fr)
        if not c:
            return
        off = (c.x - w / 2.0) / w
        if abs(off) <= tol:
            return
        f.hand.look(int(f.nav.units_for_pixels(off * w) * 0.8), 0)
        time.sleep(0.45)


