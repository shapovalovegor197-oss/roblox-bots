def maybe_rebirth(after_target: bool = False) -> None:
    """Попробовать переродиться, если похоже, что требования выполнены.

    Проверку «хватает ли» делает сам `Farmer.rebirth`: он читает окно, сверяет
    сумму и ИМЕННЫЕ требования с тем, что стоит на базе, и отказывается, если
    чего-то нет. Поэтому здесь достаточно грубого условия — иначе мы просто
    зря откроем и закроем окно.

    После удачного ребёрна требования МЕНЯЮТСЯ (следующий уровень дороже и
    просит других брейнротов), поэтому цели перечитываем сразу.

    ОТКРЫВАЕМ ОКНО РЕДКО. Замер по ночному прогону 01.09 (05:41-08:43): 90
    попыток ребёрна, каждая от «пробую» до закрытия окна — респавн, меню,
    чтение, закрытие. За те же три часа бот простоял у ленты около четверти
    времени, а ловил он там редкого легендарного, и это единственное место, где
    цель вообще может появиться. Ответ окна при этом был один и тот же 90 раз
    подряд: «не хватает Glorbo Fruttodrillo». Меняет его только НАША покупка —
    её и ждём.
    """
    if state["ребёрнов"] >= REBIRTHS_GOAL:
        return
    need = state["нужно_денег"] or 0
    cash = state["кэш"] or 0
    if cash < need and not after_target:
        return
    целей = len(state.get("цели_куплены") or [])
    свежая_покупка = целей != _reb_check["целей"]
    остыло = state["кругов"] - _reb_check["круг"] >= REBIRTH_EVERY
    if not (after_target or свежая_покупка or остыло):
        return
    _reb_check["круг"] = state["кругов"]
    _reb_check["целей"] = целей
    say("пробую ребёрн: кэш %s, нужно %s (повод: %s)"
        % (cash, need,
           "цель куплена" if (after_target or свежая_покупка) else "плановая сверка"))
    try:
        ok = f.rebirth()
    except Exception as exc:                                # noqa: BLE001
        state["сбоев"] += 1
        say("ребёрн сорвался: %s" % exc)
        return
    инфо = getattr(f, "last_rebirth_info", None)
    if инфо:
        note_targets_on_base(инфо)
    if not ok:
        return
    state["ребёрнов"] += 1
    state["цели_куплены"] = []
    say("!!! РЕБЁРН %d из %d сделан" % (state["ребёрнов"], REBIRTHS_GOAL))
    # ЦЕЛИ СБРАСЫВАЕМ. Накопление (см. read_goals) верно ВНУТРИ одного уровня,
    # но ребёрн меняет уровень, и старые требования израсходованы. Замер
    # 03.09, 08:45: сразу после первого ребёрна список стал ['Chef
    # Crabracadabra', 'Frigo Camelo', 'Glorbo Fruttodrillo'] — то есть бот
    # собрался снова покупать Chef за $150K, имея на руках $50K после
    # обнуления. Пустой список безопасен: read_goals ниже перечитает окно.
    state["все_требования"] = []
    state["цели"] = []
    state["нужно_денег"] = None
    state["денег_хватает"] = None
    # Деньги и брейнроты стёрты — перечитываем и то, и другое.
    state["кэш"] = f.read_hud_cash()
    state["кэш_старт"] = state["кэш"]
    _money.clear()
    read_goals()


def client_alive() -> bool:
    """Клиент действительно в игровом мире, а не только имеет окно."""
    try:
        return bool(enum_roblox_windows()) and f.alive_in_world()
    except Exception:                                       # noqa: BLE001
        return False


def держать_размер_окна() -> None:
    """Вернуть окно к рабочему размеру, если Roblox применил сохранённый."""
    try:
        box = f.window.client_box()
        нужно = (int(s.window["width"]), int(s.window["height"]))
        if ((box.width, box.height) == нужно and box.left >= 0 and box.top >= 0):
            return
        f.window.move_resize(0, 0, *нужно)
        новое = f.window.client_box()
        say("окно съехало на %dx%d @(%d,%d) — вернул %dx%d @(%d,%d)"
            % (box.width, box.height, box.left, box.top,
               новое.width, новое.height, новое.left, новое.top))
    except Exception as exc:                                # noqa: BLE001
        say("размер окна проверить не вышло: %s" % exc)


def стабилизировать_окно(секунд: float = 12.0) -> None:
    """Переждать поздний resize клиента перед первым маршрутом.

    Roblox иногда сначала открывает игровое окно в рабочем размере, а уже
    после появления HUD применяет сохранённые 1078x720. Один ранний замер этого
    не ловит: первый маршрут тогда идёт по координатам другого кадра. На старте
    несколько раз возвращаем геометрию и только затем нажимаем клавиши.
    """
    конец = time.time() + секунд
    while time.time() < конец:
        держать_размер_окна()
        time.sleep(min(2.0, max(0.0, конец - time.time())))
    держать_размер_окна()


def revive_client() -> bool:
    """Поднять клиент заново и пересобрать фермера на новое окно.

    Без этой проверки бот не замечает пропажи окна и продолжает водить мышью
    по рабочему столу: 31.08 клиент выбило (в игру вошли тем же аккаунтом с
    ноутбука), а цикл ещё минуту слепо тыкал курсором, пока не сработала
    защита pydirectinput от угла экрана. Ввод при этом уходил КУДА УГОДНО.
    """
    global f, _client_mutex, _client_session
    say("окна клиента нет — поднимаю заново")
    try:
        from brainbot.session import Session                # noqa: PLC0415
        from brainbot.mutex import SingletonMutex           # noqa: PLC0415
        if _client_mutex is None:
            _client_mutex = SingletonMutex()
            _client_mutex.acquire()
        for _ in range(3):
            _client_session = Session(account=s.account(ACCOUNT), settings=s)
            if _client_session.launch(приватка=PRIVATE):
                break
            time.sleep(3.0)
        else:
            say("клиент не поднялся")
            return False
        win = _client_session.window
    except Exception as exc:                                # noqa: BLE001
        say("поднять клиент не вышло: %s" % exc)
        return False
    f = Farmer(window=win, hand=Hand(win, s.input),
               tuning=FarmTuning(blind_lock=False),
               screens_dir=s.screenshots_dir)
    f.allow_wipe = not DRY_RUN
    # Session.launch подтверждает только появление окна. Внутри в этот момент
    # ещё может быть загрузочный экран без мира; ensure_connected считает его
    # нормальным, потому что там нет слова Reconnect. Ждём именно игровой HUD,
    # иначе первый прямой маршрут стартует в пустой кадр и гарантированно
    # расходует одну попытку лока.
    мир_до = time.time() + 60.0
    while time.time() < мир_до:
        if client_alive():
            break
        time.sleep(3.0)
    else:
        say("новый клиент открылся, но игровой мир не загрузился за 60 с")
        return False
    стабилизировать_окно()
    say("клиент поднят заново, hwnd=%s" % win.hwnd)
    return True


def wait_at_plate() -> None:
    """Досидеть остаток лока и вернуться. НИКУДА не идти.

    Название осталось историческим: раньше здесь бот шёл к плите заранее, чтобы
    запереться в момент истечения. Замеры 03.09 показали, что это делает ХУЖЕ.

    Почему. Надёжный лок начинается с респавна, а респавн и так возвращает на
    спавн, откуда «плита видна сразу» и замок садится за 17-18 с. Значит место,
    где мы досиживаем остаток, не имеет значения вовсе. А слепой подход уводил
    персонажа С этой хорошей точки: при живом локе плита не светится, наводиться
    не на что, и после четырёх шагов вслепую бот оказывался там, откуда её не
    видно ни сверху, ни осмотром.

    Числа (06:40-06:41): подход вслепую -> три дошага «круг не виден» -> «пад не
    опознан» -> «свечения не видно даже осмотром» -> и только потом штатный
    ритуал, который запер за 19.8 с. Дверь простояла открытой 47.1 с. Круги без
    этого подхода в том же прогоне дали 18.8 и 18.2 с.

    Пробовал и промежуточное — доводить по свечению без респавна (dc071fd,
    следом ещё раз): «заперто сразу» не появилось НИ РАЗУ за два прогона.
    """
    left = f.lock_left_now()
    say("досиживаю остаток лока: %d с" % left)
    while f.lock_left_now() > 1:
        time.sleep(0.4)


# Порядок работы, как его сформулировал пользователь: «закрыть — сбор —
# закрыть — сбор — закрыть — закуп — закрыть — продажа». Дверь закрывается
# ПЕРЕД каждым действием, а не раз в круг: пока база открыта, у нас уносят
# брейнротов, и это дороже любой упущенной покупки.
# Цель ночи — семь перерождений, а упирается всё в ОДИН брейнрот с ленты
# (деньги давно есть: 98M при требовании 35M). Поэтому лента идёт через раз,
# а не раз в пять кругов.
# База пуста (всё унесли), собирать и продавать нечего, а деньги на ребёрн
# уже есть — значит смысл только в ленте, где ждём цель. Сбор оставляем
# редким: он же проверяет, не появилось ли что-то на базе.
ДЕЙСТВИЯ = ["лента", "лента", "лента", "сбор"]
СТОИМОСТЬ = {"сбор": 25.0, "лента": 55.0, "продажа": 35.0}


# Сколько заходов на запирание делаем, прежде чем признать круг сорванным.
# Уходить к ленте с открытой дверью нельзя ни при каких обстоятельствах.
LOCK_TRIES = 4
# Дверь открыта дольше этого — кричим в лог отдельной строкой и снимаем кадр.
DOOR_ALARM = 20.0


def учесть_дверь(opened_at: float) -> None:
    """Прибавить к сумме ТОЛЬКО неучтённые секунды открытой двери.

    Раньше сюда шло `время_сейчас - opened_at`, то есть ВСЁ время с истечения
    лока. Но `opened_at` берётся из `_лок_истёк`, а он при неудачном локе не
    двигается: круг заканчивался, начинался следующий, и та же самая минута
    прибавлялась заново. Замер 06.09: прогон длился 3248 с, а сумма показывала
    8648.9 с — больше, чем прошло времени вообще. По такому числу нельзя ни
    судить о ночи, ни сравнивать прогоны, а именно им мы и мерили воровство.
    """
    учтено = max(state.get("_дверь_учтено_до") or opened_at, opened_at)
    теперь = time.time()
    state["дверь_открыта_всего"] = round(
        state.get("дверь_открыта_всего", 0.0) + max(0.0, теперь - учтено), 1)
    state["_дверь_учтено_до"] = теперь


def ensure_locked() -> bool:
    if PRIVATE:
        return True
    """Дверь закрыта? Если нет — закрыть, и только потом что-то делать.

    ПРАВИЛО ПРОВЕРКИ (02.09, прямое требование пользователя: «ты не закрываешь
    двери — делай себе правило проверки»). Отсюда нельзя выйти с открытой
    дверью молча. Каждый незакрытый заход — строка «ДВЕРЬ ОТКРЫТА N с» и кадр
    в var/screens; суммарное время открытой двери за прогон копится в
    `дверь_открыта_всего` и печатается в каждом круге и в итоговой строке.
    Проверять надо именно эту сумму, а не «вроде работает».

    До 02.09 попытка была ровно одна: `lock_with_retries(attempts=2)` не вышел —
    и круг просто заканчивался, а дверь оставалась открытой до следующего
    круга. В логе 11:05-11:09 так набежало две минуты подряд.
    """
    left = f.lock_left_now()
    if left > 5:
        f._fresh_lock = False
        return True
    if 0 < left <= 40:
        try:
            wait_at_plate()
        except Exception as exc:                            # noqa: BLE001
            say("ожидание у плиты сорвалось: %s" % exc)
    if f.lock_left_now() > 5:
        f._fresh_lock = False
        return True
    t0 = time.time()
    opened_at = state.get("_лок_истёк") or t0
    state["дверь_открыта_с"] = max(0.0, round(t0 - opened_at, 1))
    for заход in range(1, LOCK_TRIES + 1):
        left = f.lock_with_retries(attempts=2)
        открыта = round(max(0.0, time.time() - opened_at), 1)
        if left and left <= 5:
            # Остаток в одну-две секунды — это старый лок у самого истечения
            # либо ошибочно прочитанная цифра. Считать его свежим локом нельзя:
            # один такой ответ дал циклу «ЗАПЕРТО на 1 с», после чего дверь
            # оставалась открытой 133 секунды и доходных существ унесли.
            say("лок подтвердился только на %d с — жду истечения и запираю заново"
                % left)
            f.lock_until = 0.0
            time.sleep(left + 1.0)
            continue
        if left:
            state["локов"] += 1
            state["локи_секунд"].append(round(time.time() - t0, 1))
            state["_лок_истёк"] = time.time() + left
            state["дверь_открыта_с"] = открыта
            учесть_дверь(opened_at)
            state.setdefault("дверь_открыта_история", []).append(открыта)
            say("ЗАПЕРТО на %d с (за %.1f с), дверь была открыта %.1f с, "
                "всего за прогон %.0f с"
                % (left, time.time() - t0, открыта,
                   state.get("дверь_открыта_всего", 0.0)))
            # После настоящего лока камера гарантированно смотрит вдоль базы.
            # Пользуемся этим известным направлением сразу: прямой проход по
            # рядам забирает накопление, пока дверь закрыта. Позже камера уйдёт
            # к ленте, и повторить тот же маршрут без нового лока уже нельзя.
            f._fresh_lock = True
            было = state.get("кэш")
            try:
                gain = f.collect_from_spawn_rows()
                сейчас = sane_cash(было)
                note_cash(сейчас if сейчас is not None else было)
                if gain:
                    state["собрано_всего"] += gain
                    state["сборов_ноль_подряд"] = 0
                    say("сбор сразу после лока: +%.0f" % gain)
            except Exception as exc:                        # noqa: BLE001
                state["сбоев"] += 1
                say("прямой сбор после лока сорвался: %s" % exc)
            return True
        state["сбоев"] += 1
        retry_after = getattr(f, "_lock_retry_after", 0.0)
        if retry_after > time.time():
            учесть_дверь(opened_at)
            state["причина_лока"] = getattr(f, "_lock_failure", "unknown")
            say("лок приостановлен: %s; повтор после диагностики" % state["причина_лока"])
            time.sleep(min(30.0, max(0.0, retry_after - time.time())))
            return False
        say("ДВЕРЬ ОТКРЫТА %.0f с — лок не вышел (заход %d из %d), пробую снова"
            % (открыта, заход, LOCK_TRIES))
        if открыта >= DOOR_ALARM:
            f.shot("door_open")
        time.sleep(1.5)
    открыта = round(max(0.0, time.time() - opened_at), 1)
    учесть_дверь(opened_at)
    say("ДВЕРЬ НЕ ЗАКРЫЛАСЬ за %.0f с и %d заходов — к ленте НЕ иду, "
        "начинаю круг заново" % (открыта, LOCK_TRIES))
    f.shot("door_stuck")
    return False


def circle() -> None:
    if not client_alive():
        if not revive_client():
            state["сбоев"] += 1
            time.sleep(30)
            return
    if not f.ensure_connected():
        state["сбоев"] += 1
        say("клиент не вернулся в игру")
        time.sleep(30)
        return

    # 1. Когда сумма готова с запасом и текущее окно требует ровно одного
    # персонажа, на базе ещё нечего охранять. В этом узком случае не обновляем
    # замок и отдаём всё время ленте. Условие опирается на цвет коробки в окне,
    # поэтому слепое чтение или уже купленная цель режим не включат.
    need = state["нужно_денег"] or 0
    хватает = bool(state.get("денег_хватает"))
    if need and (state["кэш"] or 0) >= need * ONE_TARGET_CASH_MARGIN:
        хватает = True
    охота = bool(state["цели"]) and хватает
    одна_цель = one_target_hunt()
    state["режим_одной_цели"] = одна_цель
    if одна_цель:
        state["база_пуста"] = True
        state["цель_охоты"] = state["недостающие_цели"][0]
        if not state.get("_режим_охоты_объявлен"):
            state["_режим_охоты_объявлен"] = True
            say("РЕЖИМ ОДНОЙ ЦЕЛИ: $%.0f при пороге $%.0f, жду %s на ленте "
                "без возвратов к воротам"
                % (state["кэш"] or 0, need, state["цель_охоты"]))
    else:
        state["база_пуста"] = False
        state.pop("цель_охоты", None)
        state.pop("_режим_охоты_объявлен", None)
        if not ensure_locked():
            return

    # После обычной покупки проверяем ребёрн под замком. Единственная цель из
    # непрерывной охоты обрабатывается ниже немедленно, без лишнего пути домой.
    if not одна_цель and state.pop("проверить_ребёрн", False):
        maybe_rebirth(after_target=True)

    # 2. Одно действие — и только если на него хватит запертого времени.
    # Пока охотимся за целью при полном кошельке, всё остальное — трата
    # времени: база пуста, собирать и продавать нечего, а покупать нельзя,
    # ребёрн всё сотрёт. В таком состоянии круг = только лента.
    act = "лента" if охота else ДЕЙСТВИЯ[state["кругов"] % len(ДЕЙСТВИЯ)]
    left = 999.0 if одна_цель else f.lock_left_now()
    if left < СТОИМОСТЬ[act]:
        # Ждём НЕ НА МЕСТЕ, а стоя на плите. Раньше здесь стоял sleep: бот
        # досиживал остаток лока где придётся, лок истекал, и только потом
        # начиналась дорога к плите — то есть дверь была открыта весь путь.
        # Замер 02.09: 11:16:46 «лока осталось 18 — жду», 11:17:04 лок истёк,
        # заперто в 11:18:08 — дверь простояла открытой 63.9 с при том, что
        # бот всё это время никуда не спешил. wait_at_plate для того и написан.
        say("на «%s» нужно %.0f с, лока осталось %.0f — иду ждать НА ПЛИТУ"
            % (act, СТОИМОСТЬ[act], left))
        state["кругов"] += 1
        try:
            wait_at_plate()
        except Exception as exc:                            # noqa: BLE001
            say("ожидание у плиты сорвалось: %s" % exc)
        return

    before = state["кэш"]
    if act == "сбор":
        # Сперва по подписям «Collect $N» — это прямой признак, где лежат
        # деньги. Не вышло (подписей нет, ушли наружу) — прежний проход по
        # рядам как запасной путь.
        gain = f.collect_by_labels(budget=min(25.0, СТОИМОСТЬ["сбор"]))
        if not gain:
            gain = f.collect_back_from_plate()
        if gain:
            state["собрано_всего"] += gain
            state["сборов_ноль_подряд"] = 0
        else:
            # Ноль на сборе — единственный честный признак, что на базе не
            # осталось ни одного доходного брейнрота (см. планку в
            # worth_buying). Копим его подряд, чтобы одиночный промах прохода
            # не сходил за пустую базу.
            state["сборов_ноль_подряд"] = state.get("сборов_ноль_подряд", 0) + 1
        say("сбор: +%.0f%s" % (gain, "" if gain else " (нулевых подряд %d)"
                               % state.get("сборов_ноль_подряд", 0)))
    elif act == "продажа":
        bar = max(MIN_INCOME, (state["кэш"] or 0) / 20000.0)
        say("продажа: планка дохода %.0f/с" % bar)
        sold = [] if DRY_RUN else f.sell_below(bar, side=state.get("ряд", -1))
        if DRY_RUN:
            say("ПРОБА: продажа пропущена")
        if sold:
            state["продано"] = state.get("продано", 0) + len(sold)
            state.setdefault("продано_кого", []).extend(sold)
    elif act == "лента":
        walked = goto_belt()
        if walked is None:
            state["сбоев"] += 1
            f.shot("fail_belt")
            say("до ленты не дошёл")
        else:
            shopping((lambda: 999.0) if одна_цель else f.lock_left_now,
                     continuous=одна_цель)

    note_cash(sane_cash(before) or before)
    if одна_цель and state.pop("проверить_ребёрн", False):
        до = state["ребёрнов"]
        maybe_rebirth(after_target=True)
        # Если окно прочиталось неуверенно и попытка не прошла, следующий круг
        # сначала возьмёт замок и повторит проверку, не возвращаясь к охоте.
        if state["ребёрнов"] == до:
            state["проверить_ребёрн"] = True
    else:
        maybe_rebirth()
    state["кругов"] += 1
    say("круг %d (%s): покупок %d, ребёрнов %d, кэш %s, дверь открыта за прогон %.0f с"
        % (state["кругов"], act, state["покупок"], state["ребёрнов"], state["кэш"],
           state.get("дверь_открыта_всего", 0.0)))



